"""Finite observation scale maps via prefix projections and compatible thread spaces.

AuthorityEffect: None.
Mirrors Lean 4 constructive formalization in Limits.lean.

Key concepts:
- Stage c n: Finite observation words of length n over a carrier of size c.
- Bonding map: bond(w) forgets the last entry (w[:-1]).
- Compatible: A family of stages satisfying bond(t_{n+1}) = t_n at every scale.
- Sequence bijection: Constructive bijection between threads and infinite sequences (to_seq / of_seq).
- Eventual agreement is not compatibility: Eventual agrees after scale 2, but fails at scale 1.
- Cofinal rescaling: Restriction to even scales preserves the sequence space identically.
- Non-locality of shift: Shifting a word requires data beyond the observed prefix boundary.
- Dyadic twin separation: The sequences 0111... and 1000... are separated at scale 1,
  refusing continuum or interval identification without an explicit quotient.
"""

from __future__ import annotations

from typing import Callable, Sequence

Word = tuple[int, ...]


class LimitsError(ValueError):
    """Refusal or domain violation in the limits framework."""


def bond(word: Word) -> Word:
    """The bonding map: forget the last entry of the stage."""
    return word[:-1]


def compatible(family: Sequence[Word]) -> bool:
    """Compatibility at every scale: stage n has length n, and bond(t_{n+1}) == t_n."""
    if not family:
        return True
    for n, stage in enumerate(family):
        if len(stage) != n:
            return False
        if n + 1 < len(family):
            if bond(family[n + 1]) != stage:
                return False
    return True


def eventually_compatible(family: Sequence[Word], after: int) -> bool:
    """Lax compatibility: bonding holds only for n >= after."""
    if after >= len(family):
        return True
    return all(bond(family[n + 1]) == family[n] for n in range(after, len(family) - 1))


def of_seq(seq: Callable[[int], int], upto: int) -> tuple[Word, ...]:
    """Prefix family generated by a sequence up to scale `upto`: a compatible thread."""
    return tuple(tuple(seq(i) for i in range(n)) for n in range(upto + 1))


def to_seq(family: Sequence[Word], i: int) -> int:
    """Extract sequence entry i from thread: read index i at stage i + 1."""
    if i + 1 >= len(family):
        raise LimitsError(f"Scale {i + 1} not present in family of length {len(family)}")
    stage = family[i + 1]
    if i >= len(stage):
        raise LimitsError(f"Index {i} out of bounds for stage of length {len(stage)}")
    return stage[i]


def roundtrip_to_of_seq(seq: Callable[[int], int], upto: int) -> bool:
    """Verify to_seq(of_seq(s)) == s constructively."""
    thread = of_seq(seq, upto)
    return all(to_seq(thread, i) == seq(i) for i in range(upto))


def roundtrip_of_to_seq(family: Sequence[Word]) -> bool:
    """Verify of_seq(to_seq(t)) == t for any compatible thread."""
    if not compatible(family):
        return False
    upto = len(family) - 1
    reconstructed = of_seq(lambda i: to_seq(family, i), upto)
    return tuple(family) == reconstructed


def eventual(upto: int) -> tuple[Word, ...]:
    """Counterexample family: constant 0 except at stage 1, where it reads 1."""
    return tuple((1,) if n == 1 else (0,) * n for n in range(upto + 1))


def ebond(word: Word) -> Word:
    """Bonding for the even-scale subsystem: forget the last two entries."""
    return word[:-2]


def ecompatible(family: Sequence[Word]) -> bool:
    """Compatibility on the even-scale subsystem: stage n has length 2*n."""
    for n, stage in enumerate(family):
        if len(stage) != 2 * n:
            return False
        if n + 1 < len(family):
            if ebond(family[n + 1]) != stage:
                return False
    return True


def eof_seq(seq: Callable[[int], int], upto: int) -> tuple[Word, ...]:
    """Even-scale prefixes generated by a sequence up to scale 2*upto."""
    return tuple(tuple(seq(i) for i in range(2 * n)) for n in range(upto + 1))


def eto_seq(family: Sequence[Word], i: int) -> int:
    """Extract sequence entry i from an even thread: read index i at stage i + 1."""
    # Scale i + 1 has length 2*(i + 1), which strictly exceeds i.
    if i + 1 >= len(family):
        raise LimitsError(f"Even scale {i + 1} not present in family of length {len(family)}")
    stage = family[i + 1]
    return stage[i]


def restrict_even(family: Sequence[Word]) -> tuple[Word, ...]:
    """Restrict a full thread to its even-scale subsystem."""
    return tuple(family[2 * n] for n in range(len(family) // 2 + (1 if len(family) % 2 else 0)))


even_family = restrict_even


def shift_not_local_witness() -> tuple[Word, Word, Word, Word]:
    """Witness that word shift is not a function of observed prefixes.

    Two 3-entry words [0, 1, 2] and [0, 1, 0] share the 2-prefix [0, 1].
    Their shifted 2-prefixes are [1, 2] and [1, 0], which differ.
    Hence no prefix map phi : Stage 2 -> Stage 2 can compute the shift.
    """
    w1: Word = (0, 1, 2)
    w2: Word = (0, 1, 0)
    prefix1 = w1[:2]
    prefix2 = w2[:2]
    assert prefix1 == prefix2 == (0, 1)
    shift1 = w1[1:3]
    shift2 = w2[1:3]
    assert shift1 == (1, 2)
    assert shift2 == (1, 0)
    return w1, w2, shift1, shift2


def twin_lo(i: int) -> int:
    """Dyadic lower sequence: 0, 1, 1, 1, ..."""
    return 0 if i == 0 else 1


def twin_hi(i: int) -> int:
    """Dyadic upper sequence: 1, 0, 0, 0, ..."""
    return 1 if i == 0 else 0


def twins_differ_at_scale_one() -> bool:
    """Dyadic twins are distinguished at scale 1; refusing interval identification."""
    thread_lo = of_seq(twin_lo, 1)
    thread_hi = of_seq(twin_hi, 1)
    return thread_lo[1] != thread_hi[1]
