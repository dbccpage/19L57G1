_STEP_TREE = re.compile(r"(?<![A-Za-z0-9_./-])research/([A-Za-z0-9_-]+)(?![A-Za-z0-9_-])")


def workflow_step_trees(workflow: str, job: str) -> set[str]:
    """Trees one job's steps run or enter, read step by step without audit_estate.

    Only ``run`` values (inline or block) and ``working-directory`` values are
    read; comment lines and step names are not, so a comment naming a tree
    does not register it.
    """
    lines = workflow.replace("\r\n", "\n").split("\n")
    header = f"  {job}:"
    if header not in lines:
        raise AssertionError(f"the workflow has no '{job}:' job")
    trees: set[str] = set()
    in_block = False
    for line in lines[lines.index(header) + 1:]:
        stripped = line.strip()
        if re.match(r"^  \S", line) and not stripped.startswith("#"):
            break  # the next job
        if in_block:
            if not stripped or line.startswith(" " * 10):
                if not stripped.startswith("#"):
                    trees |= set(_STEP_TREE.findall(stripped))
                continue
            in_block = False
        if stripped.startswith("#"):
            continue
        key, sep, value = stripped.removeprefix("- ").partition(":")
        if sep and key in ("run", "working-directory"):
            if value.strip() in ("|", ">"):
                in_block = True
            else:
                trees |= set(_STEP_TREE.findall(value))
    return trees


def generated_table_trees(readme_text: str) -> set[str]:
    """Tree names in the generated block of research/README.md, read without audit_estate."""
    lines = readme_text.splitlines()
    if GENERATED_BEGIN not in lines or GENERATED_END not in lines:
        raise AssertionError("research/README.md has lost its generated-table markers")
    block = lines[lines.index(GENERATED_BEGIN) + 1 : lines.index(GENERATED_END)]
    return {m.group(1) for line in block if (m := re.match(r"^\| `([^`]+)` \|", line))}


def nodeid_counts(stdout: str) -> dict[str, int]:
    """Per-file counts from pytest nodeid lines, parsed without audit_estate."""
    counts: dict[str, int] = {}
    for line in stdout.splitlines():
        path, sep, _ = line.strip().partition("::")
        if sep and path.startswith("tests/"):
            counts[path] = counts.get(path, 0) + 1
    return counts

