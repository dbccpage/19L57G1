class TestEstateHonesty(unittest.TestCase):
    """Integrity and reconciliation tests for the research estate."""

    trees: list[ae.TreeAuditRecord]
    test_audit: dict[str, Any]
    axiom_audit: dict[str, Any]

    @classmethod
    def setUpClass(cls) -> None:
        cls.trees = ae.audit_trees(ROOT)
        cls.test_audit = ae.audit_test_counts(ROOT)
        cls.axiom_audit = ae.audit_axioms(ROOT)

    def test_all_trees_audited(self) -> None:
        """All trees declared in research/README.md exist on disk, and none is dropped."""
        self.assertGreater(len(self.trees), 0, "the tree census must not be empty")
        missing_on_disk = [t.name for t in self.trees if not t.exists_on_disk]
        self.assertEqual(missing_on_disk, [], "All declared trees must exist on disk")
        readme = (ROOT / "research" / "README.md").read_text(encoding="utf-8")
        self.assertEqual(
            {t.name for t in self.trees},
            generated_table_trees(readme),
            "the audit_estate tree census differs from the generated table in research/README.md",
        )

    def test_gate_11_ci_integration_counts(self) -> None:
        """Gate 11's trees, read two ways, agree, and none of the dated record is dropped."""
        g11_trees = [t.name for t in self.trees if t.in_verify_yml_gate11]
        local_trees = [t.name for t in self.trees if not t.in_verify_yml_gate11]
        # The auditor reads the workflow one way and the generated column of
        # research/README.md reads it another.  They differ only on `second`,
        # which the auditor counts as wired (KNOWN_AUDIT_DIFFERENCES in
        # ci/research_index.py).  This replaces the frozen local count.
        disagree = {
            t.name
            for t in self.trees
            if t.in_verify_yml_gate11 != (t.gate_11_in_readme == "workflow (gate 11)")
        }
        self.assertEqual(disagree, {"second"})
        self.assertGreater(len(local_trees), 0)
        # 2026-09-25: `len(g11_trees) == 13` and a frozen 13-name set are
        # withdrawn (see the module docstring).  The auditor's set must equal
        # the step-by-step read plus the `second` umbrella, and the step read
        # must keep every tree of the dated record.
        stepwise = workflow_step_trees(WORKFLOW_PATH.read_text(encoding="utf-8"), "research")
        self.assertEqual(set(g11_trees) - stepwise, {"second"})
        self.assertEqual(stepwise - set(g11_trees), set())
        dropped = sorted(RESEARCH_JOB_20260925 - stepwise)
        self.assertEqual(dropped, [], f"research-job trees dropped from the workflow: {dropped}")

    def test_lean_ci_axiom_gate_counts(self) -> None:
        """The lean job's research trees, read two ways, agree, and none of the dated record is dropped."""
        # 2026-09-25: "only second_nofirst and typed_translation" is withdrawn
        # (see the module docstring).
        ci_lean_trees = {t.name for t in self.trees if t.in_verify_yml_lean}
        stepwise = workflow_step_trees(WORKFLOW_PATH.read_text(encoding="utf-8"), "lean")
        declared = {t.name for t in self.trees}
        self.assertEqual(ci_lean_trees, stepwise & declared)
        self.assertEqual(stepwise - declared, set(), "the lean job runs a tree research/README.md does not list")
        dropped = sorted(LEAN_JOB_20260925 - stepwise)
        self.assertEqual(dropped, [], f"lean-job trees dropped from the workflow: {dropped}")

    def test_root_test_suite_drift_reconciled(self) -> None:
        """The live root-suite path: parser health and drift arithmetic, no frozen counts."""
        root = self.test_audit["root_suite"]
        self.assertEqual(root["collect_returncode"], 0, "root pytest collection must succeed")
        self.assertGreater(
            root["current_collected"],
            0,
            "parser must not report 0 on pytest 9 nodeid collect output",
        )
        self.assertGreater(root["current_files"], 0)
        by_file = root["counts_by_file"]
        self.assertEqual(sum(by_file.values()), root["current_collected"])
        self.assertEqual(len(by_file), root["current_files"])
        # The auditor reads the per-file summary pytest prints; an independent
        # run in nodeid form must give the same count for every file.
        res = subprocess.run(
            [sys.executable, "-m", "pytest", "tests/", "--collect-only", "-q",
             "-o", "addopts=", "-p", "no:cacheprovider"],
            cwd=ROOT,
            capture_output=True,
            text=True,
        )
        self.assertEqual(res.returncode, 0, res.stdout[-2000:] + res.stderr[-2000:])
        independent = nodeid_counts(res.stdout)
        differ = {
            path: (by_file.get(path), independent.get(path))
            for path in sorted(set(by_file) | set(independent))
            if by_file.get(path) != independent.get(path)
        }
        self.assertEqual(differ, {}, "per-file counts (auditor, independent nodeid read) differ")
        # The README row parses, is internally consistent, and the drift is
        # the difference of the two populations, whatever they are today.
        self.assertGreater(root["readme_collected"], 0)
        self.assertGreater(root["readme_files"], 0)
        self.assertEqual(root["readme_passed"] + root["readme_skipped"], root["readme_collected"])
        self.assertEqual(root["drift_collected"], root["current_collected"] - root["readme_collected"])

    def test_readme_tests_row_is_required(self) -> None:
        """A README without a parsable Tests row is an error, never the 2026-09-10 values."""
        with tempfile.TemporaryDirectory() as tmp:
            fake = Path(tmp)
            (fake / "tests").mkdir()
            (fake / "README.md").write_text("| Tests | many |\n", encoding="utf-8")
            with self.assertRaisesRegex(ValueError, "no Tests row"):
                ae.audit_test_counts(fake)

    def test_pytest_collect_parser_handles_nodeids_and_file_counts(self) -> None:
        nodeids = (
            "tests/a.py::test_one\n"
            "tests/a.py::TestC::test_two\n"
            "tests/b.py::test_x\n"
            "3 tests collected in 0.01s\n"
        )
        node_counts = ae.parse_pytest_collect_output(nodeids)
        self.assertEqual(node_counts, {"tests/a.py": 2, "tests/b.py": 1})
        self.assertEqual(sum(node_counts.values()), 3)
        old = "tests/a.py: 10\ntests/b.py: 2\n"
        self.assertEqual(
            ae.parse_pytest_collect_output(old),
            {"tests/a.py": 10, "tests/b.py": 2},
        )

