"""test_estate_honesty.py — Test suite for Target 10 Estate Honesty Pass.

Verifies:
1. Every tree declared in research/README.md exists on disk, and the auditor's
   tree census equals an independent read of the generated table.
2. The Gate 11 wiring (13 trees), cross-checked against the generated column
   of research/README.md.
3. Exact Lean CI axiom checking (2 trees in CI: second_nofirst, typed_translation).
4. Root test count drift: the live path is checked for parser health and
   drift arithmetic only.
5. Kernel axiom report integrity (every report within {propext, Quot.sound}).
6. Generation and claim hygiene of ESTATE_AUDIT_REPORT.md and RECONCILED_CLAIMS_LEDGER.md.
7. The dated 2026-09-10 record in audit_summary.json and ESTATE_AUDIT_REPORT.md.

2026-09-18: live counts are no longer asserted against frozen literals.  The
tree count (56), the local-receipt count (43), the root suite (523 collected,
41 files, README 481) and the kernel axiom report count (1530, 75 modules)
were asserted as live values; the first three went stale without anything
being wrong, and the fourth would at the next honest change.  The numbers the
2026-09-10 audit recorded are tested where they are recorded, as a dated
snapshot.  Running ``audit_estate.py --write`` overwrites that record, and the
snapshot test then fails by design.
"""

import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile
from typing import Any
import unittest

ROOT = Path(__file__).resolve().parents[2]
ESTATE_HONESTY_DIR = ROOT / "research" / "estate_honesty"
SNAPSHOT_PATH = ESTATE_HONESTY_DIR / "audit_summary.json"
REPORT_PATH = ESTATE_HONESTY_DIR / "ESTATE_AUDIT_REPORT.md"
GENERATED_BEGIN = "<!-- generated by ci/research_index.py: begin -->"
GENERATED_END = "<!-- generated by ci/research_index.py: end -->"

# The dated record the 2026-09-10 audit wrote.  These are history, not the
# current estate; the live tests below never compare against them.
SNAPSHOT_20260910 = {
    "total_trees": 48,
    "gate11_trees": 13,
    "ci_lean_trees": 2,
    "manual_lean_trees": 28,
    "root_tests_collected": 523,
    "root_tests_readme": 481,
    "test_drift": 42,
    "kernel_axioms_current": 1530,
    "kernel_axioms_historical": 1314,
    "axiom_drift": 216,
}


def generated_table_trees(readme_text: str) -> set[str]:
    """Tree names in the generated block of research/README.md, read without audit_estate."""
    lines = readme_text.splitlines()
    if GENERATED_BEGIN not in lines or GENERATED_END not in lines:
        raise AssertionError("research/README.md has lost its generated-table markers")
    block = lines[lines.index(GENERATED_BEGIN) + 1 : lines.index(GENERATED_END)]
    return {m.group(1) for line in block if (m := re.match(r"^\| `([^`]+)` \|", line))}


def nodeid_counts(stdout: str) -> dict[str, int]:
    """Per-file counts from pytest nodeid lines, parsed without audit_estate."""
    counts: dict[str, int] = {}
    for line in stdout.splitlines():
        path, sep, _ = line.strip().partition("::")
        if sep and path.startswith("tests/"):
            counts[path] = counts.get(path, 0) + 1
    return counts

for p in (str(ROOT), str(ESTATE_HONESTY_DIR)):
    if p not in sys.path:
        sys.path.insert(0, p)

import audit_estate as ae  # type: ignore[import-not-found]  # noqa: E402
import axiom_inventory as ai  # type: ignore[import-not-found]  # noqa: E402


class TestEstateHonesty(unittest.TestCase):
    """Integrity and reconciliation tests for the research estate."""

    trees: list[ae.TreeAuditRecord]
    test_audit: dict[str, Any]
    axiom_audit: dict[str, Any]

    @classmethod
    def setUpClass(cls) -> None:
        cls.trees = ae.audit_trees(ROOT)
        cls.test_audit = ae.audit_test_counts(ROOT)
        cls.axiom_audit = ae.audit_axioms(ROOT)

    def test_all_trees_audited(self) -> None:
        """All trees declared in research/README.md exist on disk, and none is dropped."""
        self.assertGreater(len(self.trees), 0, "the tree census must not be empty")
        missing_on_disk = [t.name for t in self.trees if not t.exists_on_disk]
        self.assertEqual(missing_on_disk, [], "All declared trees must exist on disk")
        readme = (ROOT / "research" / "README.md").read_text(encoding="utf-8")
        self.assertEqual(
            {t.name for t in self.trees},
            generated_table_trees(readme),
            "the audit_estate tree census differs from the generated table in research/README.md",
        )

    def test_gate_11_ci_integration_counts(self) -> None:
        """Gate 11 in .github/workflows/verify.yml wires exactly 13 trees; the rest are local receipts."""
        g11_trees = [t.name for t in self.trees if t.in_verify_yml_gate11]
        local_trees = [t.name for t in self.trees if not t.in_verify_yml_gate11]
        # The auditor reads the workflow one way and the generated column of
        # research/README.md reads it another.  They differ only on `second`,
        # which the auditor counts as wired (KNOWN_AUDIT_DIFFERENCES in
        # ci/research_index.py).  This replaces the frozen local count.
        disagree = {
            t.name
            for t in self.trees
            if t.in_verify_yml_gate11 != (t.gate_11_in_readme == "workflow (gate 11)")
        }
        self.assertEqual(disagree, {"second"})
        self.assertGreater(len(local_trees), 0)
        self.assertEqual(len(g11_trees), 13)

        expected_g11 = {
            "blind_restart", "boundary_seed", "limit_and_observer", "partial_decide",
            "portable_interface", "primitive_difference_tower", "second",
            "second_inheritance", "second_nofirst", "second_stake", "second_stream",
            "side_free", "typed_translation",
        }
        self.assertEqual(set(g11_trees), expected_g11)

    def test_lean_ci_axiom_gate_counts(self) -> None:
        """Only second_nofirst and typed_translation have Lean axiom audits run in CI."""
        ci_lean_trees = [t.name for t in self.trees if t.in_verify_yml_lean]
        self.assertEqual(set(ci_lean_trees), {"second_nofirst", "typed_translation"})

    def test_root_test_suite_drift_reconciled(self) -> None:
        """The live root-suite path: parser health and drift arithmetic, no frozen counts."""
        root = self.test_audit["root_suite"]
        self.assertEqual(root["collect_returncode"], 0, "root pytest collection must succeed")
        self.assertGreater(
            root["current_collected"],
            0,
            "parser must not report 0 on pytest 9 nodeid collect output",
        )
        self.assertGreater(root["current_files"], 0)
        by_file = root["counts_by_file"]
        self.assertEqual(sum(by_file.values()), root["current_collected"])
        self.assertEqual(len(by_file), root["current_files"])
        # The auditor reads the per-file summary pytest prints; an independent
        # run in nodeid form must give the same count for every file.
        res = subprocess.run(
            [sys.executable, "-m", "pytest", "tests/", "--collect-only", "-q",
             "-o", "addopts=", "-p", "no:cacheprovider"],
            cwd=ROOT,
            capture_output=True,
            text=True,
        )
        self.assertEqual(res.returncode, 0, res.stdout[-2000:] + res.stderr[-2000:])
        self.assertEqual(by_file, nodeid_counts(res.stdout))
        # The README row parses, is internally consistent, and the drift is
        # the difference of the two populations, whatever they are today.
        self.assertGreater(root["readme_collected"], 0)
        self.assertGreater(root["readme_files"], 0)
        self.assertEqual(root["readme_passed"] + root["readme_skipped"], root["readme_collected"])
        self.assertEqual(root["drift_collected"], root["current_collected"] - root["readme_collected"])

    def test_readme_tests_row_is_required(self) -> None:
        """A README without a parsable Tests row is an error, never the 2026-09-10 values."""
        with tempfile.TemporaryDirectory() as tmp:
            fake = Path(tmp)
            (fake / "tests").mkdir()
            (fake / "README.md").write_text("| Tests | many |\n", encoding="utf-8")
            with self.assertRaisesRegex(ValueError, "no Tests row"):
                ae.audit_test_counts(fake)

    def test_pytest_collect_parser_handles_nodeids_and_file_counts(self) -> None:
        nodeids = (
            "tests/a.py::test_one\n"
            "tests/a.py::TestC::test_two\n"
            "tests/b.py::test_x\n"
            "3 tests collected in 0.01s\n"
        )
        node_counts = ae.parse_pytest_collect_output(nodeids)
        self.assertEqual(node_counts, {"tests/a.py": 2, "tests/b.py": 1})
        self.assertEqual(sum(node_counts.values()), 3)
        old = "tests/a.py: 10\ntests/b.py: 2\n"
        self.assertEqual(
            ae.parse_pytest_collect_output(old),
            {"tests/a.py": 10, "tests/b.py": 2},
        )

    def test_mirror_refinement_was_withdrawn(self) -> None:
        self.assertFalse(
            (ROOT / "research" / "mirror_refinement").exists(),
            "Target 5 was withdrawn; MirrorRefinement.lean must not ship",
        )

    def test_reading_f_iso_does_not_claim_to_advance_distinctness(self) -> None:
        status = (ROOT / "research" / "reading_f_iso" / "STATUS.md").read_text(encoding="utf-8")
        self.assertIn("does not add a new distinctness result", status)
        self.assertIn("f_class_distinctness", status)

    def test_gate11_literal_pins_exist(self) -> None:
        """Gate 11 pinned literal test counts are present in verify.yml."""
        pins = self.test_audit["gate11_pinned_counts"]
        self.assertEqual(pins["second_stream"], 150)
        self.assertEqual(pins["boundary_seed"], 566)
        self.assertEqual(pins["second_nofirst"], 180)
        self.assertEqual(pins["side_free"], 364)
        self.assertEqual(pins["typed_translation"], 119)
        self.assertIsNotNone(pins["limit_and_observer"])

    def test_kernel_axioms_strictly_constructive(self) -> None:
        """Every kernel axiom report is strictly contained in {propext, Quot.sound}."""
        k = self.axiom_audit["kernel_axioms"]
        self.assertGreater(k["current_report_count"], 0)
        # 1314 is read from the dated file verification_20260817.md, not live.
        self.assertEqual(k["historical_count_20260817"], 1314)
        self.assertEqual(k["drift"], k["current_report_count"] - k["historical_count_20260817"])
        self.assertGreater(k["elaborated_modules"], 0)
        self.assertTrue(k["all_within_allowed"])
        self.assertEqual(k["disallowed_count"], 0)

    def test_dated_snapshot_20260910(self) -> None:
        """The 2026-09-10 record: tested where it is recorded, never against the live estate."""
        snapshot = json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))
        self.assertEqual(snapshot, SNAPSHOT_20260910)
        self.assertEqual(
            snapshot["test_drift"],
            snapshot["root_tests_collected"] - snapshot["root_tests_readme"],
        )
        self.assertEqual(
            snapshot["axiom_drift"],
            snapshot["kernel_axioms_current"] - snapshot["kernel_axioms_historical"],
        )
        # The file count and the README row of that day are recorded only in the report.
        report = REPORT_PATH.read_text(encoding="utf-8")
        self.assertIn("**Date:** 2026-09-10", report)
        self.assertIn(
            "- **Documented in root `README.md` (line 24):** "
            "`41 files, 481 collected: 480 passed / 1 skipped`",
            report,
        )
        self.assertIn(
            "- **Discovered by current `python -m pytest --collect-only`:** `41 files, 523 collected`",
            report,
        )
        self.assertIn("| **TOTAL** | **523** |", report)

    def test_research_tree_axioms_forbid_classical_choice(self) -> None:
        """No research tree with verify_lean.py permits Classical.choice."""
        inventory = ai.inspect_tree_axiom_scripts(ROOT)
        self.assertGreaterEqual(len(inventory), 28)
        for tree_name, data in inventory.items():
            self.assertFalse(
                data["permits_choice"],
                f"Tree {tree_name} permits Classical.choice!",
            )

    def test_generated_reports_exist_and_follow_claim_hygiene(self) -> None:
        """ESTATE_AUDIT_REPORT.md and RECONCILED_CLAIMS_LEDGER.md exist and observe claim hygiene."""
        audit_rep = ESTATE_HONESTY_DIR / "ESTATE_AUDIT_REPORT.md"
        claims_led = ESTATE_HONESTY_DIR / "RECONCILED_CLAIMS_LEDGER.md"

        self.assertTrue(audit_rep.is_file())
        self.assertTrue(claims_led.is_file())

        audit_text = audit_rep.read_text(encoding="utf-8")
        claims_text = claims_led.read_text(encoding="utf-8")

        # AuthorityEffect: None must be stated
        self.assertTrue("AuthorityEffect" in audit_text and "None" in audit_text)
        self.assertTrue("AuthorityEffect" in claims_text and "None" in claims_text)

        # Forbidden hype words check
        forbidden_words = [
            "weaponized",
            "flawless",
            "perfectly",
            "true intelligence",
            "mathematically verifies",
            "fundamentally",
        ]
        for word in forbidden_words:
            self.assertNotIn(f" {word} ", audit_text.lower(), f"Forbidden word '{word}' found in audit report")
            self.assertNotIn(f" {word} ", claims_text.lower(), f"Forbidden word '{word}' found in claims ledger")


if __name__ == "__main__":
    unittest.main()
