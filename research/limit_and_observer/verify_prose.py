def fail(message: str) -> None:
    print(f"FAIL: {message}")
    sys.exit(1)


@dataclass(frozen=True)
class Binding:
    """One published number, and the receipt value it must equal.

    ``pattern`` uses ``\\s+`` wherever the prose may wrap, so a reflow does not
    silently turn a binding into a stale one.  ``expected`` is a function of
    the parsed receipt rather than a literal, so the binding cannot drift into
    agreeing with itself."""

    path: str
    pattern: str
    expected: Callable[[dict[str, Any]], tuple[object, ...]]
    why: str


def _prices(r: dict[str, Any], demand: str) -> tuple[object, ...]:
    return (
        r["prices"][f"{demand}|L|mu1"]["cost"][0],
        r["prices"][f"{demand}|F|mu1"]["cost"][0],
    )


def _purchase_obs_to_lim(r: dict[str, Any]) -> tuple[object, ...]:
    rows = [
        row for row in r["comparison"]["purchase"]
        if row["first"].startswith("OBS") and row["second"].startswith("LIM")
    ]
    true_rows = [
        row for row in rows
        if row["every_minimum_of_the_first_answers_the_second"]
    ]
    return (len(rows), len(true_rows))


def _containment_mixed(r: dict[str, Any]) -> tuple[object, ...]:
    rows = [
        row for row in r["comparison"]["containment_of_canonical_key_sets"]
        if row["first"][:3] != row["second"][:3]
    ]
    return (len(rows),)


def _axiom_report_count(_r: dict[str, Any]) -> tuple[object, ...]:
    with open(AXIOMS, encoding="utf-8") as fh:
        return (len([ln for ln in fh.read().splitlines() if ln.strip()]),)


