"""Bind every number this tree PUBLISHES to the receipt it claims to report.

Run from inside ``research/limit_and_observer``:

    python verify_prose.py

Why it exists.  ``FINDINGS.md`` opens with "Every number is regenerated by
``run_price.py`` into ``receipts/price.json``; this page reports, it does not
compute" — and three of its published numbers were the refuted **predictions**
rather than the computed values, in the section published so that no finding
rests on an unchecked count.  Every gate stayed green over them: the pins, the
tests, the coverage gate, the receipt regeneration and mypy all read code and
receipts, and none of them reads prose.

So this one does.  Each binding below names a file, a pattern that must match
**exactly once**, and the receipt value the captured text must equal.  It
fails in both directions, like the estate's other censuses: a published number
that drifts from the receipt is named with its file, line and both values, and
a binding that stops matching is named as a stale binding, so deleting the
sentence is not a way to pass.

What it does NOT do.  It cannot tell whether the receipt is the right
mathematical object, and it reads only the numbers a binding names — a claim
written with no number in it is outside its reach and stays a reader's
business.  Extending the list is a deliberate edit, not a regeneration: there
is no ``--regen`` here, because a pin regenerated under a live divergence
adopts the divergence as the baseline.

AuthorityEffect: None.
"""

