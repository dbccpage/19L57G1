#: STATUS.md's prediction table, bound to the receipt's scores.  A cell naming
#: a MISS must score false and a cell naming a HIT must score true; a cell that
#: says neither, or both, is skipped by name below rather than guessed at.
SCORE_ROW = re.compile(r"^\| (P-\d+) \| [^|]* \| (?P<outcome>[^|]*) \|$", re.M)
#: These rows distinguish a scored clause from an explicitly untested one.
MIXED_ROWS = {
    "P-10": ("P-10-no-finite-delta", "P-10-smallest-extension-UNTESTED"),
    "P-18": ("P-18-no-observer-purchases-a-limit",
             "P-18-refinement-purchases-growth-UNTESTED"),
}
MIXED_OUTCOME = re.compile(
    r"first half \*\*(HIT|MISS|OPEN)\*\*, second half \*\*(OPEN|UNTESTABLE)\*\*"
)


def check_scores(receipt: dict[str, Any], text: str) -> list[str]:
    scores = receipt["predictions"]["scores"]
    problems: list[str] = []
    seen: set[str] = set()
    for m in SCORE_ROW.finditer(text):
        pid, outcome = m.group(1), m.group("outcome")
        seen.add(pid)
        line = text[: m.start()].count("\n") + 1
        if pid in MIXED_ROWS:
            first, untested = MIXED_ROWS[pid]
            parts = MIXED_OUTCOME.fullmatch(outcome.strip())
            first_label = ("OPEN" if scores.get(first) is None else
                           "HIT" if scores[first] else "MISS")
            if (parts is None or first not in scores or untested not in scores
                    or bool(scores.get(untested))
                    or parts.group(1) != first_label):
                problems.append(
                    f"STATUS.md:{line}: {pid} mixed outcome does not match "
                    "its scored and explicitly untested clauses"
                )
            continue
        if pid not in scores:
            problems.append(
                f"STATUS.md:{line}: {pid} is tabulated but the receipt scores "
                f"no such prediction"
            )
            continue
        says_miss = "MISS" in outcome
        says_hit = "HIT" in outcome
        if scores[pid] is None:
            if "OPEN" not in outcome or says_hit or says_miss:
                problems.append(f"STATUS.md:{line}: {pid} is uncompleted and must say OPEN")
            continue
        if says_miss == says_hit:
            problems.append(
                f"STATUS.md:{line}: {pid}'s outcome cell says neither HIT nor "
                f"MISS, or both: {outcome.strip()!r}"
            )
            continue
        if says_hit is not bool(scores[pid]):
            problems.append(
                f"STATUS.md:{line}: {pid} is tabulated {outcome.strip()!r} "
                f"but the receipt scores it {bool(scores[pid])}"
            )
    expected_rows = {k for k in scores if re.fullmatch(r"P-\d+", k)} | set(MIXED_ROWS)
    for pid in sorted(expected_rows):
        if pid not in seen:
            problems.append(
                f"STATUS.md: the receipt scores {pid} but no row tabulates it"
            )
    return problems


def main() -> None:
    if not os.path.isfile(RECEIPT):
        fail("receipts/price.json is missing; run run_price.py first")
    with open(RECEIPT, encoding="utf-8") as fh:
        receipt: dict[str, Any] = json.load(fh)

    if not BINDINGS:
        fail("the binding list is empty; the check would be vacuous")

    cache: dict[str, str] = {}

    def text_of(name: str) -> str:
        # CRLF is normalised away before matching.  These files are not marked
        # ``-text`` -- only the receipts and the two frozen inputs are -- so a
        # Windows checkout with ``core.autocrlf`` on presents them with CRLF,
        # and a pattern anchored at end-of-line would then match nothing and
        # report every binding stale on one platform and clean on another.
        if name not in cache:
            with open(os.path.join(HERE, name), encoding="utf-8") as fh:
                cache[name] = fh.read().replace("\r\n", "\n")
        return cache[name]

    problems: list[str] = []
    for b in BINDINGS:
        text = text_of(b.path)
        found = list(re.finditer(b.pattern, text))
        if len(found) != 1:
            problems.append(
                f"{b.path}: the binding for {b.why} matched {len(found)} "
                f"times, expected exactly 1. If the prose moved, move the "
                f"binding with it; do not delete it."
            )
            continue
        m = found[0]
        line = text[: m.start()].count("\n") + 1
        got = tuple(m.groups())
        want = tuple(str(v) for v in b.expected(receipt))
        if len(got) != len(want):
            problems.append(
                f"{b.path}:{line}: the binding for {b.why} captured "
                f"{len(got)} values but the receipt supplies {len(want)}"
            )
            continue
        if got != want:
            problems.append(
                f"{b.path}:{line}: {b.why}: published {list(got)}, "
                f"receipt has {list(want)}"
            )

    problems.extend(check_scores(receipt, text_of("STATUS.md")))

    if problems:
        for p in problems:
            print(f"FAIL: {p}")
        fail(f"{len(problems)} published value(s) disagree with the receipt")
    print(
        f"limit_and_observer prose clean: {len(BINDINGS)} published values "
        f"bound to receipts/price.json, prediction table consistent"
    )


if __name__ == "__main__":
    main()
