def identifier_token(name: str) -> re.Pattern[str]:
    return re.compile(r"(?<![\w])" + re.escape(name) + r"(?![\w])")


def comparison_base() -> str:
    """The commit this branch's own changes are measured against: the tip
    of `main` this branch has merged.  NOT the manifest snapshot, which is
    where the pins are taken and moves for a different reason.  An
    unresolvable base FAILS; an unavailable scan is not a clean scan."""
    for ref in ("origin/main", "main"):
        proc = subprocess.run(
            ["git", "merge-base", ref, "HEAD"],
            capture_output=True, text=True, cwd=REPO, check=False,
        )
        if proc.returncode == 0 and proc.stdout.strip():
            return proc.stdout.strip()
    raise ValueError("no comparison base; the scope scan cannot run")


def head_commit() -> str:
    proc = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        capture_output=True, text=True, cwd=REPO, check=False,
    )
    if proc.returncode != 0 or not proc.stdout.strip():
        raise ValueError("git rev-parse HEAD failed; the scope scan cannot run")
    return proc.stdout.strip()


def changed_paths(base: str, head: str) -> list[str]:
    """Every path this branch's own commits touch, plus every pending
    write in the worktree.

    Rename detection is off deliberately: otherwise a move out of a sealed
    tree can be shown only under its allowed destination, concealing the
    removed source.  MERGE commits are skipped, because their first-parent
    diff is the whole incoming side of a merge from `main` and is not this
    rung's writing; every other commit on this branch is this rung's, and
    the sealed-path scan below reads the whole branch diff as well, so a
    path smuggled in through a merge is still seen.
    """
    rows = subprocess.run(
        ["git", "rev-list", "--parents", f"{base}..{head}"],
        capture_output=True, text=True, cwd=REPO, check=False,
    )
    if rows.returncode != 0:
        raise ValueError("the branch commit census is unavailable")
    lines = rows.stdout.splitlines()
    if base != head and not lines:
        raise ValueError("the branch commit census is empty ahead of its base")
    commits: list[list[str]] = []
    for line in lines:
        ids = line.split()
        if len(ids) < 2 or any(re.fullmatch(r"[0-9a-f]{40}", i) is None for i in ids):
            raise ValueError("malformed branch commit census")
        if len(ids) > 2:
            continue
        diff = subprocess.run(
            ["git", "diff", "--no-renames", "--name-only", "-z", ids[1], ids[0], "--"],
            capture_output=True, cwd=REPO, check=False,
        )
        if diff.returncode != 0:
            raise ValueError("a branch commit path census is unavailable")
        commits.append(nul_paths(diff.stdout, population="branch commit"))
    pending_paths: list[str] = []
    pending = subprocess.run(
        ["git", "status", "--porcelain", "-z", "--untracked-files=all"],
        capture_output=True, cwd=REPO, check=False,
    )
    if pending.returncode != 0:
        raise ValueError("the pending-write census is unavailable")
    for item in pending.stdout.split(b"\0"):
        if len(item) > 3:
            pending_paths.append(item[3:].decode("utf-8"))
    return rung_scope(commits, pending_paths)


def rung_scope(commits: list[list[str]], pending: list[str]) -> list[str]:
    """The paths of this rung's own commits, plus pending writes.

    A commit belongs to this rung when it touches the write root; a commit
    that mixes the rung with anything else still exposes every one of its
    paths, so it still fails the scope tests.  A branch with no such commit
    and no pending write under the write root is another tree's branch, and
    its writes are not this rung's (second_nofirst's rule, 2026-09-23
    repair by the coordinator: this scan used to attribute every branch to
    this rung, and so failed on any other pull request that touched a
    research tree).
    """
    owned = [paths for paths in commits if any(p.startswith(WRITE_ROOT + "/") for p in paths)]
    if owned or any(p.startswith(WRITE_ROOT + "/") for p in pending):
        return sorted({p for paths in owned for p in paths} | set(pending))
    return []


def whole_branch_paths(base: str, head: str) -> list[str]:
    diff = subprocess.run(
        ["git", "diff", "--no-renames", "--name-only", "-z", base, head, "--"],
        capture_output=True, cwd=REPO, check=False,
    )
    if diff.returncode != 0:
        raise ValueError("the whole-branch diff is unavailable")
    return nul_paths(diff.stdout, population="whole branch")


def removed_lines(base: str, path: str) -> list[str]:
    proc = subprocess.run(
        ["git", "diff", "--no-renames", "-U0", base, "--", path],
        capture_output=True, text=True, cwd=REPO, check=False,
    )
    if proc.returncode != 0:  # pragma: no cover - git is present
        raise RuntimeError(f"git diff failed for {path}")
    return [
        line
        for line in proc.stdout.splitlines()
        if line.startswith("-") and not line.startswith("---")
    ]


class CensusScan(unittest.TestCase):
    def test_the_write_root_carries_no_watched_term(self) -> None:
        """The repository's own prose census, over this tree only.  A hit
        names the file, the line and the token."""
        watched = census.load(REPO / census.WATCHLIST_REL)["watched"]
        assert isinstance(watched, dict)
        hits: list[str] = []
        for rel, text in readable(tracked_write_root_files()):
            for hit in census.scan_text(text, watched):
                hits.append(f"{rel}:{hit.line}: {hit.surface}")
        self.assertEqual(hits, [])

    def test_the_scanner_would_fire(self) -> None:
        """NEGATIVE: the census bites.  A probe text carrying a watched
        term is found, so the clean result above is a measurement."""
        watched = census.load(REPO / census.WATCHLIST_REL)["watched"]
        assert isinstance(watched, dict)
        probe = next(iter(watched))
        found = [
            digest
            for digest in watched
            if digest == probe
        ]
        self.assertEqual(found, [probe])
        self.assertEqual(census.scan_text("topology", {census.digest("topology"): "x"})[0].surface, "topology")

    def test_the_census_pin_is_not_touched_by_this_rung(self) -> None:
        proc = subprocess.run(
            ["git", "status", "--porcelain", "--", census.WATCHLIST_REL],
            capture_output=True, text=True, cwd=REPO, check=False,
        )
        self.assertEqual(proc.returncode, 0)
        self.assertEqual(proc.stdout.strip(), "")

    def test_no_denylist_identifier_appears_in_the_write_root(self) -> None:
        denylist = working_denylist()
        self.assertEqual(len(denylist), 102)
        hits: list[str] = []
        for rel, text in readable(tracked_write_root_files()):
            for name in denylist:
                if identifier_token(name).search(text):
                    hits.append(f"{rel}: {name}")
        self.assertEqual(hits, [])

    def test_no_glossary_term_appears_in_the_write_root(self) -> None:
        watched = {digest: "glossary" for digest in GLOSSARY_DIGESTS}
        hits: list[str] = []
        for rel, text in readable(tracked_write_root_files()):
            for hit in census.scan_text(text, watched):
                hits.append(f"{rel}:{hit.line}")
        self.assertEqual(hits, [])

    def test_the_glossary_scan_would_fire(self) -> None:
        """NEGATIVE: the matcher fires on a term whose digest is in the
        set it is given.  The barred terms are reconstructed NOWHERE: the
        probe is a made-up word, added to a copy of the digest set, which
        is the same code path the scan above runs.  What this shows is
        that the scan sees a term it is told about; that the fourteen
        digests are digests of the barred terms is the sibling rung's
        record, carried here by value."""
        self.assertTrue(all(len(digest) == 64 for digest in GLOSSARY_DIGESTS))
        self.assertEqual(len(set(GLOSSARY_DIGESTS)), 14)
        probe = "zzzprobeterm"
        watched = {digest: "glossary" for digest in GLOSSARY_DIGESTS}
        watched[census.digest(probe)] = "probe"
        hits = census.scan_text(f"a {probe} here", watched)
        self.assertEqual([hit.surface for hit in hits], [probe])


class ScopeScan(unittest.TestCase):
    def setUp(self) -> None:
        self.base = comparison_base()
        self.head = head_commit()

    def test_the_scan_sees_this_branch_at_all(self) -> None:
        """Not a vacuous pass: the branch must have written something.

        Two situations are SKIPPED by name, never passed silently (the
        second_nofirst rule; coordinator repair 2026-09-23, because this test
        failed on `main` as soon as the rung had merged): HEAD is the
        comparison base, so no branch is under test; or the branch has
        commits and none of them is this rung's.
        """
        if self.base == self.head:
            self.skipTest(f"HEAD is the comparison base ({self.base[:12]}); no branch is under test")
        paths = changed_paths(self.base, self.head)
        if not paths:
            self.skipTest("this branch carries no commit of this rung; it is another tree's branch")
        self.assertTrue(any(p.startswith(WRITE_ROOT + "/") for p in paths))

    def test_the_rung_scope_rule(self) -> None:
        """The ownership rule on synthetic commits: a rung commit counts,
        a sibling commit does not, a mixed commit exposes every path."""
        rung = [f"{WRITE_ROOT}/response_rows.py"]
        sibling = ["research/other/verify_pins.py"]
        self.assertEqual(rung_scope([sibling], []), [])
        self.assertEqual(rung_scope([rung, sibling], []), rung)
        mixed = rung_scope([rung + sibling], [])
        self.assertIn("research/other/verify_pins.py", mixed)
        self.assertEqual(rung_scope([sibling], [f"{WRITE_ROOT}/new.py"]), [f"{WRITE_ROOT}/new.py"])

    def test_this_branch_touches_nothing_outside_the_declared_scope(self) -> None:
        allowed = set(APPEND_ONLY) | set(GENERATED)
        outside = [
            path
            for path in changed_paths(self.base, self.head)
            if not path.startswith(WRITE_ROOT + "/") and path not in allowed
        ]
        self.assertEqual(outside, [])

    def test_no_sealed_path_is_touched(self) -> None:
        """Read over the WHOLE branch diff, merges included, so a sealed
        path cannot arrive through a merge commit unseen."""
        touched = [
            path
            for path in whole_branch_paths(self.base, self.head)
            if path.startswith(SEALED_PREFIXES)
        ]
        self.assertEqual(touched, [])

    def test_no_sibling_research_tree_is_written(self) -> None:
        allowed = set(APPEND_ONLY) | set(GENERATED)
        written = [
            path
            for path in changed_paths(self.base, self.head)
            if path.startswith("research/")
            and not path.startswith(WRITE_ROOT + "/")
            and path not in allowed
        ]
        self.assertEqual(written, [])

    def test_the_two_shared_edits_are_append_only(self) -> None:
        if self.base != self.head and not changed_paths(self.base, self.head):
            self.skipTest("this branch carries no commit of this rung; its shared edits are not this rung's")
        for path in APPEND_ONLY:
            self.assertEqual(removed_lines(self.base, path), [], path)

    def test_every_generated_view_names_the_command_that_writes_it(self) -> None:
        """A generated view is rewritten by a named command, never edited
        by hand.  The command is recorded here and in STATUS.md; that it
        was RUN is a receipt, recorded there and not provable from the
        bytes alone."""
        for path, command in GENERATED.items():
            self.assertTrue((REPO / path).exists(), path)
            self.assertTrue(command.startswith("python ci/"), path)

    def test_a_path_outside_the_scope_would_be_named(self) -> None:
        """NEGATIVE: the scope scan bites.  A path that is neither inside
        the write root nor declared is reported by name."""
        allowed = set(APPEND_ONLY) | set(GENERATED)
        probe = ["paper/paper.md", f"{WRITE_ROOT}/response_rows.py"]
        outside = [
            path
            for path in probe
            if not path.startswith(WRITE_ROOT + "/") and path not in allowed
        ]
        self.assertEqual(outside, ["paper/paper.md"])


class ObstructionScan(unittest.TestCase):
    def test_no_file_reports_the_obstruction_as_discharged(self) -> None:
        hits: list[str] = []
        for rel, text in readable(tracked_write_root_files()):
            for number, line in enumerate(text.split("\n"), start=1):
                for pattern in OBSTRUCTION_PATTERNS:
                    if re.search(pattern, line, re.IGNORECASE):
                        hits.append(f"{rel}:{number}")
        self.assertEqual(hits, [])

    def test_the_obstruction_scan_would_fire(self) -> None:
        """NEGATIVE: the scan bites on each of its three shapes."""
        obs = "obstr" + "uction"
        probes = (
            f"the standing {obs} is " + "clo" + "sed by this rung",
            "OB-1 has been " + "supers" + "eded here",
            "this rung " + "answers" + f" the sealed {obs}",
        )
        for probe in probes:
            self.assertTrue(
                any(re.search(p, probe, re.IGNORECASE) for p in OBSTRUCTION_PATTERNS),
                probe,
            )

    def test_the_ledger_quotes_the_leftover_verbatim(self) -> None:
        """Rung three's leftover X-6, and X-6 as rung nine carries it, are
        quoted from their pinned spans and are not edited.  Compared
        against the blobs AT THE SNAPSHOT."""
        manifest = json.loads(
            (HERE / "SOURCE_MANIFEST.json").read_text(encoding="utf-8")
        )
        ledger = (HERE / "CLAIM_LEDGER.md").read_text(encoding="utf-8")
        for suffix, first in (("second_index/STATUS.md", 165), ("second_response/STATUS.md", 212)):
            span = next(
                item
                for item in manifest["spans"]
                if item["path"].endswith(suffix) and item["first_line"] == first
            )
            blob = subprocess.run(
                ["git", "show", f"{manifest['snapshot_commit']}:{span['path']}"],
                capture_output=True, cwd=REPO, check=True,
            ).stdout.decode("utf-8").replace("\r\n", "\n").split("\n")
            quoted = blob[span["first_line"] - 1 : span["last_line"]]
            for line in quoted:
                self.assertIn(line.strip(), ledger)


