@dataclass(frozen=True)
class LocalEvalDerivable(LocalizedTransition):
    """Pure internal evaluation: checks derivability of instance in current regime."""

    form: int
    args: tuple[int, ...]

    def __init__(self, form: int, args: tuple[int, ...]) -> None:
        super().__init__(action_type="LOCAL_EVAL_DERIVABLE")
        object.__setattr__(self, "form", _require_int(form, "form"))
        if not isinstance(args, tuple) or any(
            not isinstance(arg, int) or isinstance(arg, bool) for arg in args
        ):
            raise TypeError("args must be a tuple of ints")
        object.__setattr__(self, "args", args)

    def parameters_repr(self) -> tuple[str, ...]:
        args_str = ",".join(str(a) for a in self.args)
        return (str(self.form), args_str)

    def apply(
        self, regime: Regime, registers: tuple[int, ...]
    ) -> tuple[Regime, tuple[int, ...], tuple[int, ...]]:
        if not (0 <= self.form < len(regime.forms)):
            raise AdmissionError(f"unknown form {self.form}")
        if len(self.args) != regime.forms[self.form]:
            raise AdmissionError(
                f"form {self.form} has arity {regime.forms[self.form]}, got {len(self.args)}"
            )
        if not all(0 <= a < len(regime.data) for a in self.args):
            raise AdmissionError(f"instance arguments out of range: {self.args}")

        is_der = 1 if derivable(regime, (self.form, self.args)) else 0
        readout = (is_der,)
        return regime, registers, readout


@dataclass(frozen=True)
class LocalObserveProfile(LocalizedTransition):
    """Pure internal evaluation: computes context indices satisfied by datum profile."""

    datum: int

    def __init__(self, datum: int) -> None:
        super().__init__(action_type="LOCAL_OBSERVE_PROFILE")
        object.__setattr__(self, "datum", _require_int(datum, "datum"))

    def parameters_repr(self) -> tuple[str, ...]:
        return (str(self.datum),)

    def apply(
        self, regime: Regime, registers: tuple[int, ...]
    ) -> tuple[Regime, tuple[int, ...], tuple[int, ...]]:
        if not (0 <= self.datum < len(regime.data)):
            raise AdmissionError(f"datum index out of range: {self.datum}")

        all_ctxs = contexts(regime)
        prof = profile(regime, self.datum)
        # Store sorted indices of matching contexts as readout
        matched_indices = tuple(
            idx for idx, c in enumerate(all_ctxs) if c in prof
        )
        return regime, registers, matched_indices


