@dataclass(frozen=True)
class EnclosedCarrier:
    """Carrier state enclosing relational regime, internal observer trace, and registers."""

    regime: Regime
    trace: InternalTrace
    local_registers: tuple[int, ...]
    step_count: int

    def __post_init__(self) -> None:
        _require_int(self.step_count, "step_count")
        if self.step_count < 0:
            raise ValueError(f"step_count must be non-negative, got {self.step_count}")
        if any(
            not isinstance(value, int) or isinstance(value, bool)
            for value in self.local_registers
        ):
            raise TypeError("local_registers must contain only ints")

    @classmethod
    def genesis(
        cls, num_registers: int = 4, base_regime: Regime = EMPTY
    ) -> EnclosedCarrier:
        """Construct genesis carrier state with empty trace and zeroed registers."""
        _require_int(num_registers, "num_registers")
        if num_registers < 0:
            raise ValueError(f"num_registers must be non-negative, got {num_registers}")
        return cls(
            regime=base_regime,
            trace=InternalTrace(),
            local_registers=tuple(0 for _ in range(num_registers)),
            step_count=0,
        )

    def carrier_digest(self) -> str:
        """Compute exact content digest of carrier components."""
        return compute_carrier_digest(
            self.regime, self.local_registers, self.step_count
        )

    def step_localized(self, transition: LocalizedTransition) -> EnclosedCarrier:
        """Execute a localized rewrite step within the carrier.

        State evaluation and record-keeping occur purely within the carrier.
        """
        if self.trace.length != self.step_count or not self.trace.is_valid_chain():
            raise ValueError("Carrier trace is not a valid prefix for localized stepping")
        if self.trace.latest is not None and self.trace.latest.state_digest != self.carrier_digest():
            raise ValueError("Carrier state does not match its latest trace record")
        next_regime, next_registers, readout = transition.apply(
            self.regime, self.local_registers
        )
        next_step = self.step_count + 1
        state_digest = compute_carrier_digest(
            next_regime, next_registers, next_step
        )

        prev_hash = (
            self.trace.latest.record_hash if self.trace.latest else "GENESIS"
        )
        record = ObserverRecord.create(
            step=self.step_count,
            transition_kind=transition.action_type,
            local_input=transition.parameters_repr(),
            local_readout=readout,
            state_digest=state_digest,
            prev_record_hash=prev_hash,
        )
        next_trace = self.trace.append(record)
        return EnclosedCarrier(
            regime=next_regime,
            trace=next_trace,
            local_registers=next_registers,
            step_count=next_step,
        )


@dataclass(frozen=True)
class InvariantCheckResult:
    """Outcome of internal trace invariant evaluation."""

    valid: bool
    violations: tuple[str, ...]
    steps_verified: int

    @property
    def is_valid(self) -> bool:
        return self.valid


class TraceInvariantChecker:
    """Checker verifying internal trace invariants without external prefix inspection."""

    @staticmethod
    def check_step_transition(
        prev: EnclosedCarrier,
        curr: EnclosedCarrier,
        transition: LocalizedTransition,
    ) -> InvariantCheckResult:
        """Verify single-step localized transition invariants."""
        violations: list[str] = []

        if not prev.trace.is_valid_chain():
            violations.append("Previous trace failed internal chain validity check")
        if not curr.trace.is_valid_chain():
            violations.append("Current trace failed internal chain validity check")

        # 1. Monotonic increment of step count
        if curr.step_count != prev.step_count + 1:
            violations.append(
                f"Step count mismatch: expected {prev.step_count + 1}, got {curr.step_count}"
            )

        # 2. Monotonic appending of trace length
        if curr.trace.length != prev.trace.length + 1:
            violations.append(
                f"Trace length mismatch: expected {prev.trace.length + 1}, got {curr.trace.length}"
            )

        # 3. Immutability of past trace entries
        if not curr.trace.is_monotone_extension_of(prev.trace):
            violations.append(
                "Past trace entries modified or inconsistent with previous trace"
            )

        # 4. Chaining of latest record
        latest = curr.trace.latest
        if latest is None:
            violations.append("Current trace has no latest record")
        else:
            if not latest.verify_integrity():
                violations.append("Latest record failed internal integrity check")

            expected_prev_hash = (
                prev.trace.latest.record_hash if prev.trace.latest else "GENESIS"
            )
            if latest.prev_record_hash != expected_prev_hash:
                violations.append(
                    f"Chaining failure: expected prev_hash {expected_prev_hash}, got {latest.prev_record_hash}"
                )

            if latest.step != prev.step_count:
                violations.append(
                    f"Record step mismatch: expected {prev.step_count}, got {latest.step}"
                )
            if latest.transition_kind != transition.action_type:
                violations.append("Record transition kind does not match transition")
            if latest.local_input != transition.parameters_repr():
                violations.append("Record local input does not match transition parameters")

            # 5. State correspondence
            if latest.state_digest != curr.carrier_digest():
                violations.append(
                    "Record state digest does not match current carrier digest"
                )

        # 6. Local evaluation reflection: check that transition evaluation on prev carrier
        # yields the state and readout observed in curr carrier.
        try:
            exp_regime, exp_regs, exp_readout = transition.apply(
                prev.regime, prev.local_registers
            )
            if curr.regime != exp_regime:
                violations.append("Carrier regime does not match local evaluation outcome")
            if curr.local_registers != exp_regs:
                violations.append("Carrier registers do not match local evaluation outcome")
            if latest and latest.local_readout != exp_readout:
                violations.append("Record readout does not match local evaluation outcome")
        except Exception as exc:
            violations.append(f"Local evaluation re-execution error: {exc}")

        return InvariantCheckResult(
            valid=len(violations) == 0,
            violations=tuple(violations),
            steps_verified=1,
        )

    @staticmethod
    def check_trace_integrity(trace: InternalTrace) -> InvariantCheckResult:
        """Verify static integrity of an internal trace."""
        violations: list[str] = []
        if not trace.is_valid_chain():
            violations.append("Trace failed internal chain validity check")
        return InvariantCheckResult(
            valid=len(violations) == 0,
            violations=tuple(violations),
            steps_verified=trace.length,
        )

    @staticmethod
    def check_carrier_path(
        path: Sequence[EnclosedCarrier],
        transitions: Optional[Sequence[LocalizedTransition]] = None,
    ) -> InvariantCheckResult:
        """Verify invariants across a multi-step sequence of carriers."""
        violations: list[str] = []
        if not path:
            return InvariantCheckResult(
                valid=False,
                violations=("Carrier path census is empty",),
                steps_verified=0,
            )

        # Verify genesis
        first = path[0]
        if first.step_count != 0:
            violations.append(f"Genesis step count must be 0, got {first.step_count}")
        if first.trace.length != 0:
            violations.append(
                f"Genesis trace length must be 0, got {first.trace.length}"
            )
        if any(value != 0 for value in first.local_registers):
            violations.append("Genesis registers must all be zero")

        if transitions is not None and len(transitions) != len(path) - 1:
            violations.append(
                f"Transition count {len(transitions)} does not match step count {len(path) - 1}"
            )

        # Verify each consecutive step
        for k in range(len(path) - 1):
            prev_c = path[k]
            curr_c = path[k + 1]

            # Invariant: step increment
            if curr_c.step_count != prev_c.step_count + 1:
                violations.append(
                    f"Step {k}->{k+1}: invalid step_count transition {prev_c.step_count} -> {curr_c.step_count}"
                )

            # Invariant: trace length increment
            if curr_c.trace.length != prev_c.trace.length + 1:
                violations.append(
                    f"Step {k}->{k+1}: invalid trace length transition {prev_c.trace.length} -> {curr_c.trace.length}"
                )

            # Invariant: immutability of all past entries
            for j in range(prev_c.trace.length):
                if curr_c.trace.records[j] != prev_c.trace.records[j]:
                    violations.append(
                        f"Step {k}->{k+1}: past record at index {j} was modified"
                    )

            # Invariant: state correspondence
            if curr_c.trace.latest:
                if curr_c.trace.latest.state_digest != curr_c.carrier_digest():
                    violations.append(
                        f"Step {k}->{k+1}: latest record state digest does not match carrier digest"
                    )

            # If transitions are provided, verify local evaluation consistency
            if transitions is not None and k < len(transitions):
                step_res = TraceInvariantChecker.check_step_transition(
                    prev_c, curr_c, transitions[k]
                )
                if not step_res.valid:
                    for v in step_res.violations:
                        violations.append(f"Step {k}->{k+1}: {v}")

        # Check full trace chain of final carrier
        final_trace = path[-1].trace
        if not final_trace.is_valid_chain():
            violations.append("Final carrier trace failed chain validity")

        return InvariantCheckResult(
            valid=len(violations) == 0,
            violations=tuple(violations),
            steps_verified=len(path) - 1,
        )

    @staticmethod
    def detect_retrocausal_tampering(
        carrier: EnclosedCarrier, modified_past_record_index: int
    ) -> bool:
        """Attempt to detect if a past record in carrier trace was tampered with.

        Returns True if tampering is detected (invariants violated).
        """
        if modified_past_record_index < 0 or modified_past_record_index >= carrier.trace.length:
            return False
        return not carrier.trace.is_valid_chain()
