def _require_int(value: object, field_name: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool):
        raise TypeError(f"{field_name} must be an int, got {type(value).__name__}")
    return value


def _require_str(value: object, field_name: str) -> str:
    if not isinstance(value, str):
        raise TypeError(f"{field_name} must be a str, got {type(value).__name__}")
    return value


def compute_record_hash(
    step: int,
    transition_kind: str,
    local_input: Sequence[str],
    local_readout: Sequence[int],
    state_digest: str,
    prev_record_hash: str,
) -> str:
    """Compute exact deterministic SHA-256 hash for an observer record."""
    _require_int(step, "step")
    if step < 0:
        raise ValueError(f"step must be non-negative, got {step}")
    _require_str(transition_kind, "transition_kind")
    if any(not isinstance(value, str) for value in local_input):
        raise TypeError("local_input must contain only strings")
    if any(
        not isinstance(value, int) or isinstance(value, bool)
        for value in local_readout
    ):
        raise TypeError("local_readout must contain only ints")
    _require_str(state_digest, "state_digest")
    _require_str(prev_record_hash, "prev_record_hash")
    payload = json.dumps(
        {
            "local_input": list(local_input),
            "local_readout": list(local_readout),
            "prev_record_hash": prev_record_hash,
            "state_digest": state_digest,
            "step": step,
            "transition_kind": transition_kind,
        },
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def compute_carrier_digest(
    r: Regime, registers: tuple[int, ...], step_count: int
) -> str:
    """Compute exact deterministic SHA-256 content digest for an enclosed carrier state."""
    _require_int(step_count, "step_count")
    if step_count < 0:
        raise ValueError(f"step_count must be non-negative, got {step_count}")
    if any(
        not isinstance(value, int) or isinstance(value, bool) for value in registers
    ):
        raise TypeError("registers must contain only ints")
    sorted_insts = sorted(r.insts, key=lambda x: (x[0], x[1]))
    payload = json.dumps(
        {
            "data": list(r.data),
            "forms": list(r.forms),
            "insts": [[form, list(args)] for form, args in sorted_insts],
            "registers": list(registers),
            "requirements": [list(pair) for pair in sorted(r.reqs)],
            "rules": sorted(r.rules),
            "step": step_count,
        },
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class ObserverRecord:
    """Discrete observation record generated by an internal observer rewrite step.

    Attributes:
        step: Non-negative integer index of this discrete step.
        transition_kind: Name of the localized transition rule executed.
        local_input: Deterministic representation of inputs supplied to the transition.
        local_readout: Deterministic local observation or evaluation outcome.
        state_digest: Exact SHA-256 digest of the carrier state produced by this step.
        prev_record_hash: Hash of the immediately preceding record, or 'GENESIS'.
        record_hash: Exact SHA-256 digest of this record's contents.
    """

    step: int
    transition_kind: str
    local_input: tuple[str, ...]
    local_readout: tuple[int, ...]
    state_digest: str
    prev_record_hash: str
    record_hash: str

    @classmethod
    def create(
        cls,
        step: int,
        transition_kind: str,
        local_input: Sequence[str],
        local_readout: Sequence[int],
        state_digest: str,
        prev_record_hash: str,
    ) -> ObserverRecord:
        """Create an observer record with computed hash."""
        r_hash = compute_record_hash(
            step,
            transition_kind,
            local_input,
            local_readout,
            state_digest,
            prev_record_hash,
        )
        return cls(
            step=step,
            transition_kind=transition_kind,
            local_input=tuple(local_input),
            local_readout=tuple(local_readout),
            state_digest=state_digest,
            prev_record_hash=prev_record_hash,
            record_hash=r_hash,
        )

    def verify_integrity(self) -> bool:
        """Check whether record hash matches its content."""
        expected = compute_record_hash(
            self.step,
            self.transition_kind,
            self.local_input,
            self.local_readout,
            self.state_digest,
            self.prev_record_hash,
        )
        return self.record_hash == expected


@dataclass(frozen=True)
class InternalTrace:
    """Immutable sequence of observer records maintained directly inside the carrier."""

    records: tuple[ObserverRecord, ...] = ()

    @property
    def length(self) -> int:
        """Return the count of records in this trace."""
        return len(self.records)

    @property
    def latest(self) -> Optional[ObserverRecord]:
        """Return the most recent record, or None if trace is empty."""
        return self.records[-1] if self.records else None

    def append(self, record: ObserverRecord) -> InternalTrace:
        """Return a new trace with record appended at the end."""
        return InternalTrace(self.records + (record,))

    def is_valid_chain(self) -> bool:
        """Validate continuous integrity and chaining from step 0."""
        if not self.records:
            return True
        for i, rec in enumerate(self.records):
            if not rec.verify_integrity():
                return False
            if rec.step != i:
                return False
            if i == 0:
                if rec.prev_record_hash != "GENESIS":
                    return False
            else:
                if rec.prev_record_hash != self.records[i - 1].record_hash:
                    return False
        return True

    def is_monotone_extension_of(self, earlier: InternalTrace) -> bool:
        """Check that self extends earlier trace without altering past entries."""
        if self.length < earlier.length:
            return False
        for i in range(earlier.length):
            if self.records[i] != earlier.records[i]:
                return False
        if self.length == earlier.length + 1:
            new_rec = self.records[-1]
            expected_prev = earlier.latest.record_hash if earlier.latest else "GENESIS"
            if new_rec.prev_record_hash != expected_prev:
                return False
            if new_rec.step != earlier.length:
                return False
        return True


@dataclass(frozen=True)
class LocalizedTransition:
    """Base class for localized rewrite steps in the internal observer sub-grammar."""

    action_type: str

    def parameters_repr(self) -> tuple[str, ...]:
        """Return deterministic string representation of parameters."""
        return ()

    def apply(
        self, regime: Regime, registers: tuple[int, ...]
    ) -> tuple[Regime, tuple[int, ...], tuple[int, ...]]:
        """Execute local state evaluation.

        Takes only current carrier components (regime, registers). Does not
        consult historical trace prefixes or external metatheoretic oracles.

        Returns:
            (next_regime, next_registers, local_readout)
        """
        raise NotImplementedError("Subclasses must implement apply")


