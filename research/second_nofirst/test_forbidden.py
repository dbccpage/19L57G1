def tracked_write_root_files() -> list[pathlib.Path]:
    proc = subprocess.run(
        [
            "git", "ls-files", "-z", "--cached", "--others",
            "--exclude-standard", "--", WRITE_ROOT,
        ],
        capture_output=True,
        cwd=REPO,
        check=False,
    )
    if proc.returncode != 0:  # pragma: no cover - git is present in CI
        raise RuntimeError("git ls-files failed; the write-root scan is unavailable")
    return [REPO / relative for relative in nul_paths(proc.stdout, population="tracked")]


def readable(paths: list[pathlib.Path]) -> list[tuple[str, str]]:
    files: list[tuple[str, str]] = []
    for path in paths:
        if path.is_symlink():
            raise ValueError(f"refusing to scan through symlink {path}")
        try:
            raw = path.read_bytes()
        except OSError as exc:
            raise ValueError(f"cannot read tracked file {path}") from exc
        if b"\0" in raw:
            raise ValueError(f"tracked file contains NUL bytes and cannot be scanned: {path}")
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise ValueError(f"tracked file is not UTF-8 and cannot be scanned: {path}") from exc
        rel = path.relative_to(REPO).as_posix()
        files.append((rel, text))
    return files


def working_denylist() -> list[str]:
    payload = json.loads(
        (REPO / "contact" / "analysis" / "contact_countermodels.json").read_text(
            encoding="utf-8"
        )
    )
    block = payload["denylist"]
    subtracted = set(block["subtracted_as_native_or_core"])
    return [n for n in block["full_census"] if n not in subtracted]


def identifier_token(name: str) -> re.Pattern[str]:
    return re.compile(r"(?<![\w])" + re.escape(name) + r"(?![\w])")


def comparison_base() -> str | None:
    """The commit this branch's own changes are measured against.

    NOT the manifest snapshot.  The snapshot is where the pins are taken,
    and it is the right base for a pin.  It is the WRONG base for "what did
    this branch write", because `main` moves: rung one landed after this
    rung launched, so a diff from the snapshot now shows rung one's whole
    tree as though this branch had written it.  The right base is the tip of
    `main` that this branch has merged, which is what `git merge-base`
    returns once the merge is in.

    Returns None when no base can be resolved, and the caller FAILS rather
    than passes.  An unavailable scan is not a clean scan.
    """
    for ref in ("origin/main", "main"):
        proc = subprocess.run(
            ["git", "merge-base", ref, "HEAD"],
            capture_output=True, text=True, cwd=REPO, check=False,
        )
        if proc.returncode == 0 and proc.stdout.strip():
            return proc.stdout.strip()
    return None


def head_commit() -> str:
    """The commit under test, so the guard can tell "no branch" from "no
    diff". Failing closed: an unreadable HEAD is not an excuse to skip."""
    proc = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        capture_output=True, text=True, cwd=REPO, check=False,
    )
    if proc.returncode != 0 or not proc.stdout.strip():
        raise ValueError("git rev-parse HEAD failed; the scope scan cannot run")
    return proc.stdout.strip()


def nul_paths(raw: bytes, *, population: str) -> list[str]:
    """Decode a NUL-delimited Git path population, failing closed."""
    if not raw:
        return []
    if not raw.endswith(b"\0"):
        raise ValueError(f"{population} path population lacks trailing NUL")
    items = raw[:-1].split(b"\0")
    if any(not item for item in items):
        raise ValueError(f"{population} path population contains an empty item")
    out: list[str] = []
    for item in items:
        try:
            out.append(item.decode("utf-8"))
        except UnicodeDecodeError as exc:
            raise ValueError(f"a {population} path is not UTF-8") from exc
    return out


def changed_paths(base: str) -> list[str]:
    """Every tracked or untracked path in the current worktree scope.

    Rename detection is disabled deliberately.  Otherwise Git may present a
    move out of a sealed tree only under its allowed destination and conceal
    the removed source.  Untracked paths are enumerated repository-wide: an
    outside-root write is still outside scope before it is added to Git.
    """
    diff = subprocess.run(
        ["git", "diff", "--no-renames", "--name-only", "-z", base, "--"],
        capture_output=True, cwd=REPO, check=False,
    )
    if diff.returncode != 0:  # pragma: no cover - git is present in CI
        raise RuntimeError("git diff failed; the committed-scope scan is unavailable")
    untracked = subprocess.run(
        ["git", "ls-files", "-z", "--others", "--exclude-standard", "--"],
        capture_output=True, cwd=REPO, check=False,
    )
    if untracked.returncode != 0:  # pragma: no cover - git is present in CI
        raise RuntimeError(
            "git ls-files failed; the untracked-scope scan is unavailable"
        )
    paths = nul_paths(diff.stdout, population="changed")
    paths.extend(nul_paths(untracked.stdout, population="untracked"))
    return sorted(set(paths))


def census_pin_status() -> str:
    proc = subprocess.run(
        ["git", "status", "--porcelain", "--", census.WATCHLIST_REL],
        capture_output=True,
        text=True,
        cwd=REPO,
        check=False,
    )
    if proc.returncode != 0:  # pragma: no cover - git is present in CI
        raise RuntimeError("git status failed; the census-pin check is unavailable")
    return proc.stdout.strip()


def removed_append_lines(base: str, path: str) -> list[str]:
    proc = subprocess.run(
        ["git", "diff", "--no-renames", "-U0", base, "--", path],
        capture_output=True,
        text=True,
        cwd=REPO,
        check=False,
    )
    if proc.returncode != 0:  # pragma: no cover - git is present in CI
        raise RuntimeError(f"git diff failed; append-only check unavailable for {path}")
    return [
        line
        for line in proc.stdout.splitlines()
        if line.startswith("-") and not line.startswith("---")
    ]


class CensusScan(unittest.TestCase):
    def test_the_write_root_carries_no_watched_term(self) -> None:
        """The repository's own prose census, over this tree only.  A hit
        here fails this rung rather than the root gate, and the pin is not
        regenerated to make it pass."""
        watched = census.load(REPO / census.WATCHLIST_REL)["watched"]
        assert isinstance(watched, dict)
        hits: list[str] = []
        for rel, text in readable(tracked_write_root_files()):
            for hit in census.scan_text(text, watched):
                hits.append(f"{rel}:{hit.line}: {hit.surface}")
        self.assertEqual(hits, [])

    def test_the_scanner_would_fire(self) -> None:
        """NEGATIVE: the clean scan above is a check and not an inert call.

        FOUND LIVE while writing this file, and the same defect the root
        gate recorded against its own test: an earlier version named three
        watched nouns as probes, and the census then flagged this file.
        A test for a gate must not be the thing the gate looks for.  So the
        probe is a nonsense word added to a COPY of the watched map: the
        scanner is exercised without any watched term entering the tree.
        """
        watched = census.load(REPO / census.WATCHLIST_REL)["watched"]
        assert isinstance(watched, dict)
        self.assertGreater(len(watched), 0)
        probe = "zzzprobenoun"
        self.assertEqual(census.scan_text(f"a {probe} of it", watched), [])
        seeded = dict(watched)
        seeded[census.digest(probe)] = "probe"
        hits = census.scan_text(f"a {probe} of it", seeded)
        self.assertEqual([h.surface for h in hits], [probe])

    def test_the_census_pin_is_not_touched_by_this_rung(self) -> None:
        self.assertEqual(census_pin_status(), "")


