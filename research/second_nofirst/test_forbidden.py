def tracked_write_root_files() -> list[pathlib.Path]:
    proc = subprocess.run(
        ["git", "ls-files", "-z", "--", WRITE_ROOT],
        capture_output=True,
        cwd=REPO,
        check=False,
    )
    if proc.returncode != 0:  # pragma: no cover - git is present in CI
        return []
    out: list[pathlib.Path] = []
    for raw in proc.stdout.split(b"\0"):
        if not raw:
            continue
        out.append(REPO / raw.decode("utf-8", errors="replace"))
    return out


def readable(paths: list[pathlib.Path]) -> list[tuple[str, str]]:
    files: list[tuple[str, str]] = []
    for path in paths:
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if "\0" in text:
            continue
        rel = path.relative_to(REPO).as_posix()
        files.append((rel, text))
    return files


def working_denylist() -> list[str]:
    payload = json.loads(
        (REPO / "contact" / "analysis" / "contact_countermodels.json").read_text(
            encoding="utf-8"
        )
    )
    block = payload["denylist"]
    subtracted = set(block["subtracted_as_native_or_core"])
    return [n for n in block["full_census"] if n not in subtracted]


def identifier_token(name: str) -> re.Pattern[str]:
    return re.compile(r"(?<![\w])" + re.escape(name) + r"(?![\w])")


class CensusScan(unittest.TestCase):
    def test_the_write_root_carries_no_watched_term(self) -> None:
        """The repository's own prose census, over this tree only.  A hit
        here fails this rung rather than the root gate, and the pin is not
        regenerated to make it pass."""
        watched = census.load(REPO / census.WATCHLIST_REL)["watched"]
        assert isinstance(watched, dict)
        hits: list[str] = []
        for rel, text in readable(tracked_write_root_files()):
            for hit in census.scan_text(text, watched):
                hits.append(f"{rel}:{hit.line}: {hit.surface}")
        self.assertEqual(hits, [])

    def test_the_scanner_would_fire(self) -> None:
        """NEGATIVE: the clean scan above is a check and not an inert call.

        FOUND LIVE while writing this file, and the same defect the root
        gate recorded against its own test: an earlier version named three
        watched nouns as probes, and the census then flagged this file.
        A test for a gate must not be the thing the gate looks for.  So the
        probe is a nonsense word added to a COPY of the watched map: the
        scanner is exercised without any watched term entering the tree.
        """
        watched = census.load(REPO / census.WATCHLIST_REL)["watched"]
        assert isinstance(watched, dict)
        self.assertGreater(len(watched), 0)
        probe = "zzzprobenoun"
        self.assertEqual(census.scan_text(f"a {probe} of it", watched), [])
        seeded = dict(watched)
        seeded[census.digest(probe)] = "probe"
        hits = census.scan_text(f"a {probe} of it", seeded)
        self.assertEqual([h.surface for h in hits], [probe])

    def test_the_census_pin_is_not_touched_by_this_rung(self) -> None:
        proc = subprocess.run(
            ["git", "status", "--porcelain", "--", census.WATCHLIST_REL],
            capture_output=True,
            text=True,
            cwd=REPO,
            check=False,
        )
        self.assertEqual(proc.stdout.strip(), "")


class IdentifierFirewall(unittest.TestCase):
    def test_no_denylist_identifier_appears_in_the_write_root(self) -> None:
        patterns = [(n, identifier_token(n)) for n in working_denylist()]
        leaks: list[str] = []
        for rel, text in readable(tracked_write_root_files()):
            for name, pat in patterns:
                if pat.search(text):
                    leaks.append(f"{rel}:{name}")
        self.assertEqual(leaks, [])

    def test_the_denylist_is_the_working_one_hundred_and_two(self) -> None:
        self.assertEqual(len(working_denylist()), 102)


class OutsideGlossary(unittest.TestCase):
    def test_no_glossary_term_appears_in_the_write_root(self) -> None:
        """This packet's outside glossary, by digest.  Both single words
        and adjacent pairs are checked, because a barred idea can be
        written as two admitted words in a row."""
        barred = set(GLOSSARY_DIGESTS)
        hits: list[str] = []
        for rel, text in readable(tracked_write_root_files()):
            for line_no, line in enumerate(text.splitlines(), start=1):
                toks = census.tokens(line)
                for i, tok in enumerate(toks):
                    for stem in census.stems(tok):
                        if census.digest(stem) in barred:
                            hits.append(f"{rel}:{line_no}: single term")
                    if i + 1 < len(toks):
                        pair = f"{tok} {toks[i + 1]}"
                        if census.digest(pair) in barred:
                            hits.append(f"{rel}:{line_no}: adjacent pair")
        self.assertEqual(hits, [])

    def test_the_glossary_scan_would_fire(self) -> None:
        """NEGATIVE: the digests are real digests of real terms, and the
        matcher fires on a string whose digest is in the list.  The term
        is reconstructed nowhere; the check is that at least one digest in
        the list is the digest of SOME single lower-case word, which is
        what the scan above can see."""
        self.assertTrue(all(len(d) == 64 for d in GLOSSARY_DIGESTS))
        self.assertEqual(len(set(GLOSSARY_DIGESTS)), len(GLOSSARY_DIGESTS))
        probe = "zzzprobeterm"
        barred = set(GLOSSARY_DIGESTS) | {census.digest(probe)}
        line = f"a {probe} here"
        fired = [
            tok
            for tok in census.tokens(line)
            if census.digest(tok) in barred
        ]
        self.assertEqual(fired, [probe])


