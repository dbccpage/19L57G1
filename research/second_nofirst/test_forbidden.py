class SealedObstruction(unittest.TestCase):
    def test_no_file_reports_the_obstruction_as_discharged(self) -> None:
        """FW-OB1.  A plain scan with no carve-out for negation."""
        pats = [re.compile(p, re.IGNORECASE) for p in OBSTRUCTION_PATTERNS]
        exempt = set(REFUSAL_LINE_DIGESTS)
        hits: list[str] = []
        used: set[str] = set()
        for rel, text in readable(tracked_write_root_files()):
            for line_no, line in enumerate(text.splitlines(), start=1):
                mark = census.digest(line.strip())
                for pat in pats:
                    if not pat.search(line):
                        continue
                    if mark in exempt:
                        used.add(mark)
                        continue
                    hits.append(f"{rel}:{line_no}: {pat.pattern}")
        self.assertEqual(hits, [])
        # A pinned exemption that no longer matches anything is a stale
        # pin, and is failed in that direction too.
        self.assertEqual(used, exempt)

    def test_an_exempted_line_loses_its_exemption_when_reworded(self) -> None:
        """NEGATIVE: the exemption is by digest of exact bytes.  The line
        is READ from the frozen PROMPT.md rather than written here -- both
        so this file does not itself carry a barred shape, and so the pin
        is checked against the real frozen text.  Appending to the line
        changes its digest and withdraws the exemption."""
        pats = [re.compile(p, re.IGNORECASE) for p in OBSTRUCTION_PATTERNS]
        prompt = (HERE / "PROMPT.md").read_text(encoding="utf-8")
        matching = [
            line.strip()
            for line in prompt.splitlines()
            if any(pat.search(line) for pat in pats)
        ]
        self.assertEqual(len(matching), 1)
        self.assertIn(census.digest(matching[0]), set(REFUSAL_LINE_DIGESTS))
        self.assertNotIn(
            census.digest(matching[0] + " and this rung did it"),
            set(REFUSAL_LINE_DIGESTS),
        )

    def test_the_obstruction_scan_would_fire(self) -> None:
        """NEGATIVE: each barred shape is matched by a probe sentence.  The
        probes are ASSEMBLED FROM FRAGMENTS, exactly as the forbidden-token
        patterns of `verify_lean.py` are, so that this file does not itself
        carry the shapes it bars."""
        pats = [re.compile(p, re.IGNORECASE) for p in OBSTRUCTION_PATTERNS]
        obs = "obstr" + "uction"
        probes = (
            f"the standing {obs} is " + "clo" + "sed by this rung",
            "OB-1 has been " + "supers" + "eded here",
            "this rung " + "answers" + f" the sealed {obs}",
        )
        for probe in probes:
            self.assertTrue(
                any(pat.search(probe) for pat in pats),
                f"no pattern fired on {probe!r}",
            )

    def test_the_ledger_quotes_the_obstruction_verbatim(self) -> None:
        """FW-OB1's other half: the sealed sentence is present, unedited,
        and matches its pinned span byte for byte."""
        manifest = json.loads(
            (HERE / "SOURCE_MANIFEST.json").read_text(encoding="utf-8")
        )
        span = next(
            s
            for s in manifest["spans"]
            if s["path"] == "paper/paper.md" and s["first_line"] == 488
        )
        raw = subprocess.run(
            ["git", "show", f"{manifest['snapshot_commit']}:paper/paper.md"],
            capture_output=True,
            cwd=REPO,
            check=True,
        ).stdout.decode("utf-8")
        lines = raw.replace("\r\n", "\n").split("\n")
        quoted = "\n".join(lines[span["first_line"] - 1 : span["last_line"]]) + "\n"
        self.assertEqual(
            hashlib.sha256(quoted.encode("utf-8")).hexdigest(), span["sha256"]
        )
        ledger = (HERE / "CLAIM_LEDGER.md").read_text(encoding="utf-8")
        for line in quoted.strip().split("\n"):
            self.assertIn(line.strip(), ledger)


