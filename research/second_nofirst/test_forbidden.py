class OutsideGlossary(unittest.TestCase):
    def test_no_glossary_term_appears_in_the_write_root(self) -> None:
        """This packet's outside glossary, by digest.  Both single words
        and adjacent pairs are checked, because a barred idea can be
        written as two admitted words in a row."""
        barred = set(GLOSSARY_DIGESTS)
        hits: list[str] = []
        for rel, text in readable(tracked_write_root_files()):
            for line_no, line in enumerate(text.splitlines(), start=1):
                toks = census.tokens(line)
                for i, tok in enumerate(toks):
                    for stem in census.stems(tok):
                        if census.digest(stem) in barred:
                            hits.append(f"{rel}:{line_no}: single term")
                    if i + 1 < len(toks):
                        pair = f"{tok} {toks[i + 1]}"
                        if census.digest(pair) in barred:
                            hits.append(f"{rel}:{line_no}: adjacent pair")
        self.assertEqual(hits, [])

    def test_the_glossary_scan_would_fire(self) -> None:
        """NEGATIVE: the digests are real digests of real terms, and the
        matcher fires on a string whose digest is in the list.  The term
        is reconstructed nowhere; the check is that at least one digest in
        the list is the digest of SOME single lower-case word, which is
        what the scan above can see."""
        self.assertTrue(all(len(d) == 64 for d in GLOSSARY_DIGESTS))
        self.assertEqual(len(set(GLOSSARY_DIGESTS)), len(GLOSSARY_DIGESTS))
        probe = "zzzprobeterm"
        barred = set(GLOSSARY_DIGESTS) | {census.digest(probe)}
        line = f"a {probe} here"
        fired = [
            tok
            for tok in census.tokens(line)
            if census.digest(tok) in barred
        ]
        self.assertEqual(fired, [probe])


class WriteRootScan(unittest.TestCase):
    """FW-SEAL, FW-SHARE: what this branch wrote, measured against the tip
    of `main` it has merged rather than against the pin snapshot."""

    def setUp(self) -> None:
        base = comparison_base()
        if base is None:  # pragma: no cover - a resolvable base exists here
            self.fail("no comparison base; the committed-scope scan cannot run")
        self.base = base
        self.head = head_commit()
        self.changed = changed_paths(base)

    def test_this_branch_touches_nothing_outside_the_write_root(self) -> None:
        stray = [
            path
            for path in self.changed
            if not path.startswith(WRITE_ROOT + "/") and path not in APPEND_ONLY
        ]
        self.assertEqual(stray, [])

    def test_the_scan_sees_this_branch_at_all(self) -> None:
        """NEGATIVE: the boundary scan above must not pass by reading nothing.

        An empty change set makes `test_this_branch_touches_nothing_outside_
        the_write_root` trivially green, so something has to notice. What that
        something may NOT do is assert through the two situations where an
        empty or foreign change set is the correct answer:

        * **HEAD is the comparison base.** On `main` after this rung merged
          there is no branch under test at all, and the diff is empty because
          the work already landed. An earlier version of this test asserted
          through that case and so failed on `main` at `7d2e6e86` -- a red
          gate reporting nothing wrong, which is the failure the register
          exists to prevent, committed by the guard against it.
        * **The branch has commits, none under this write root.** It is
          another rung's branch. This rung's boundary is not what it is
          testing, and demanding this rung's files on it is the same
          over-broad scope the `second_stream` verifier was repaired for.

        Both are SKIPPED and named, never passed silently. The case the guard
        exists for survives: HEAD ahead of the base with an EMPTY change set
        means the base machinery returned a diff of nothing while there was
        something to diff, and that still fails.
        """
        if self.base == self.head:
            self.skipTest(
                f"HEAD is the comparison base ({self.base[:12]}); no branch is "
                "under test, so there is nothing for the boundary scan to read"
            )
        self.assertTrue(
            self.changed,
            f"HEAD {self.head[:12]} is ahead of the base {self.base[:12]} but "
            "the change set is empty; the boundary scan would pass by reading "
            "nothing",
        )
        mine = [p for p in self.changed if p.startswith(WRITE_ROOT + "/")]
        if not mine:
            self.skipTest(
                f"this branch changed {len(self.changed)} path(s), none under "
                f"{WRITE_ROOT}/; it is not this rung's branch"
            )

    def test_no_sealed_path_is_touched(self) -> None:
        sealed = (
            "prompt/", "paper/", "code/", "lean4/", "artifacts/", "ci/",
            "tests/", "CLAUDE.md", "pyproject.toml", "requirements.txt",
            "research/second/SEED.md", "research/second/PLAN.md",
        )
        self.assertEqual([p for p in self.changed if p.startswith(sealed)], [])

    def test_no_sibling_research_tree_is_written(self) -> None:
        siblings = [
            path
            for path in self.changed
            if path.startswith("research/")
            and not path.startswith(WRITE_ROOT + "/")
            and path != "research/second/MANUAL.md"
        ]
        self.assertEqual(siblings, [])

    def test_the_two_shared_edits_are_append_only(self) -> None:
        """The charter permits two edits outside the write root and permits
        them ONLY as appends.  A removed line in either is a violation, and
        this counts them."""
        base = comparison_base()
        assert base is not None
        for path in APPEND_ONLY:
            self.assertEqual(
                removed_append_lines(base, path), [], f"{path} is not append-only"
            )


class SealedObstruction(unittest.TestCase):
    def test_no_file_reports_the_obstruction_as_discharged(self) -> None:
        """FW-OB1.  A plain scan with no carve-out for negation."""
        pats = [re.compile(p, re.IGNORECASE) for p in OBSTRUCTION_PATTERNS]
        exempt = set(REFUSAL_LINE_DIGESTS)
        hits: list[str] = []
        used: set[str] = set()
        for rel, text in readable(tracked_write_root_files()):
            for line_no, line in enumerate(text.splitlines(), start=1):
                mark = census.digest(line.strip())
                for pat in pats:
                    if not pat.search(line):
                        continue
                    if mark in exempt:
                        used.add(mark)
                        continue
                    hits.append(f"{rel}:{line_no}: {pat.pattern}")
        self.assertEqual(hits, [])
        # A pinned exemption that no longer matches anything is a stale
        # pin, and is failed in that direction too.
        self.assertEqual(used, exempt)

    def test_an_exempted_line_loses_its_exemption_when_reworded(self) -> None:
        """NEGATIVE: the exemption is by digest of exact bytes.  The line
        is READ from the frozen PROMPT.md rather than written here -- both
        so this file does not itself carry a barred shape, and so the pin
        is checked against the real frozen text.  Appending to the line
        changes its digest and withdraws the exemption."""
        pats = [re.compile(p, re.IGNORECASE) for p in OBSTRUCTION_PATTERNS]
        prompt = (HERE / "PROMPT.md").read_text(encoding="utf-8")
        matching = [
            line.strip()
            for line in prompt.splitlines()
            if any(pat.search(line) for pat in pats)
        ]
        self.assertEqual(len(matching), 1)
        self.assertIn(census.digest(matching[0]), set(REFUSAL_LINE_DIGESTS))
        self.assertNotIn(
            census.digest(matching[0] + " and this rung did it"),
            set(REFUSAL_LINE_DIGESTS),
        )

    def test_the_obstruction_scan_would_fire(self) -> None:
        """NEGATIVE: each barred shape is matched by a probe sentence.  The
        probes are ASSEMBLED FROM FRAGMENTS, exactly as the forbidden-token
        patterns of `verify_lean.py` are, so that this file does not itself
        carry the shapes it bars."""
        pats = [re.compile(p, re.IGNORECASE) for p in OBSTRUCTION_PATTERNS]
        obs = "obstr" + "uction"
        probes = (
            f"the standing {obs} is " + "clo" + "sed by this rung",
            "OB-1 has been " + "supers" + "eded here",
            "this rung " + "answers" + f" the sealed {obs}",
        )
        for probe in probes:
            self.assertTrue(
                any(pat.search(probe) for pat in pats),
                f"no pattern fired on {probe!r}",
            )

    def test_the_ledger_quotes_the_obstruction_verbatim(self) -> None:
        """FW-OB1's other half: the sealed sentence is present, unedited,
        and matches its pinned span byte for byte."""
        manifest = json.loads(
            (HERE / "SOURCE_MANIFEST.json").read_text(encoding="utf-8")
        )
        span = next(
            s
            for s in manifest["spans"]
            if s["path"] == "paper/paper.md" and s["first_line"] == 488
        )
        raw = subprocess.run(
            ["git", "show", f"{manifest['snapshot_commit']}:paper/paper.md"],
            capture_output=True,
            cwd=REPO,
            check=True,
        ).stdout.decode("utf-8")
        lines = raw.replace("\r\n", "\n").split("\n")
        quoted = "\n".join(lines[span["first_line"] - 1 : span["last_line"]]) + "\n"
        self.assertEqual(
            hashlib.sha256(quoted.encode("utf-8")).hexdigest(), span["sha256"]
        )
        ledger = (HERE / "CLAIM_LEDGER.md").read_text(encoding="utf-8")
        for line in quoted.strip().split("\n"):
            self.assertIn(line.strip(), ledger)


class ScannerFailureTests(unittest.TestCase):
    def test_unreadable_file_fails_closed(self) -> None:
        path = pathlib.Path("probe.md")
        with mock.patch.object(pathlib.Path, "read_bytes", side_effect=OSError("probe")):
            with self.assertRaisesRegex(ValueError, "cannot read tracked file"):
                readable([path])

    def test_non_utf8_file_fails_closed(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            path = pathlib.Path(tmp) / "probe.md"
            path.write_bytes(b"plain prefix\xff")
            with self.assertRaisesRegex(ValueError, "not UTF-8"):
                readable([path])

    def test_nul_file_fails_closed(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            path = pathlib.Path(tmp) / "probe.md"
            path.write_bytes(b"plain\x00text")
            with self.assertRaisesRegex(ValueError, "contains NUL"):
                readable([path])

    def test_git_diff_failure_is_not_an_empty_change_set(self) -> None:
        failed = subprocess.CompletedProcess(
            args=["git", "diff"], returncode=2, stdout=b"", stderr=b"probe failure"
        )
        with mock.patch.object(subprocess, "run", return_value=failed):
            with self.assertRaisesRegex(RuntimeError, "git diff failed"):
                changed_paths("probe")

    def test_untracked_census_failure_is_not_an_empty_change_set(self) -> None:
        diff = subprocess.CompletedProcess(
            args=["git", "diff"], returncode=0, stdout=b"probe.py\0", stderr=b""
        )
        failed = subprocess.CompletedProcess(
            args=["git", "ls-files"], returncode=2, stdout=b"", stderr=b"probe"
        )
        with mock.patch.object(subprocess, "run", side_effect=[diff, failed]):
            with self.assertRaisesRegex(RuntimeError, "untracked-scope scan"):
                changed_paths("probe")

