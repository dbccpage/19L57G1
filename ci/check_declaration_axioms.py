"""Declaration-level axiom census of the sealed Lean development.

Usage (after ``lake build`` in the Lean package):

    python ci/check_declaration_axioms.py [--lean-dir lean4] [--pin FILE]
                                          [--raw-out FILE] [--print-census]

A LOCAL TOOL, not a registered gate: ``.github/workflows/verify.yml`` does
not run it, and nothing in the gate census reads its output.  Registering it
is a contract amendment, which is the author's act.

What it closes, and what it does not
------------------------------------
The audit that ``ci/check_lean_audit.py`` performs reads the ``#print
axioms`` reports in a build log.  Those reports cover the root's
hand-maintained inventory in ``lean4/Derivation.lean`` and the THEOREMS of
the parked modules named in ``lean4/ParkedAudit.lean`` (internal details and
constructor-generated lemmas excluded).  A DEFINITION that depends on
``Classical.choice`` and that no reported theorem reaches is therefore
reported by nothing, and neither is a theorem the root inventory happens not
to list.

This tool reads the compiled environment instead of the log.  It writes a
generated census file to a temporary directory OUTSIDE the repository,
imports the root plus every module in ``artifacts/elaborated_modules.txt``,
and runs it with ``lake env lean`` from the Lean package directory.  For
every constant that each module named ``Derivation`` or ``Derivation.*``
added -- read from ``Environment.getModuleIdx?``/``ModuleData.constNames``,
the enumeration ``lean4/ParkedAudit.lean`` already uses -- it collects the
axioms: theorems, definitions, instances, generated constants and internal
details alike.  It prints one summary line with counts by kind and fails
naming each constant whose axioms leave ``{propext, Quot.sound}``.

``lean4/ParkedAudit.lean`` is outside the scope BY MODULE: it is a
top-level apparatus file, not a ``Derivation`` module.  Its constants are
imported and read too, but any of them outside the whitelist is printed on
one informational witness line, never as a failure.  That line is the
measured witness that the definition exclusion in the theorem-only audit is
not hypothetical.

What a pass does NOT say: the axioms are those Lean records for each
constant, so a pass is a claim about the compiled environment of the tree
that was built, not about any source text; and a constant outside every
``Derivation`` module (another top-level ``lean4/*.lean``) is outside its
reach except as ``ParkedAudit`` is read for the witness.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import re
import shutil
import subprocess
import sys
import tempfile
from collections import Counter
from collections.abc import Callable, Sequence
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ALLOWED_AXIOMS = frozenset({"propext", "Quot.sound"})
ROOT_MODULE = "Derivation"
WITNESS_MODULE = "ParkedAudit"
CENSUS_FILE_NAME = "DeclarationAxiomCensus.lean"
DEFAULT_TIMEOUT = 1800
KINDS = (
    "axiom",
    "constructor",
    "definition",
    "inductive",
    "opaque",
    "quotient",
    "recursor",
    "theorem",
)
MODULE_NAME = re.compile(r"^Derivation(\.[A-Za-z_][A-Za-z0-9_]*)+$")
PREFIXES = ("DECLAX_MODULE ", "DECLAX_CONST ", "DECLAX_UNRESOLVED ", "DECLAX_END ")

CENSUS_TEMPLATE = """\
-- Generated by ci/check_declaration_axioms.py.  NOT a repository file: it is
-- written to a temporary directory outside the repository and run with
-- `lake env lean` from the Lean package directory, then discarded.
import Lean.Elab.Command
import Lean.Util.CollectAxioms
import Lean.Meta.Instances
import Lean.Data.Json
@@IMPORTS@@

open Lean Elab Command

def declaxKind : ConstantInfo -> String
  | .axiomInfo _ => "axiom"
  | .defnInfo _ => "definition"
  | .thmInfo _ => "theorem"
  | .opaqueInfo _ => "opaque"
  | .quotInfo _ => "quotient"
  | .inductInfo _ => "inductive"
  | .ctorInfo _ => "constructor"
  | .recInfo _ => "recursor"

run_cmd do
  let env <- getEnv
  let mut modules : Nat := 0
  let mut constants : Nat := 0
  for (modName, data) in env.header.moduleNames.zip env.header.moduleData do
    let scope :=
      if (`@@ROOT@@).isPrefixOf modName then "sealed"
      else if modName == `@@WITNESS@@ then "witness"
      else ""
    if scope != "" then
      modules := modules + 1
      liftIO <| IO.println ("DECLAX_MODULE " ++ (Json.mkObj [
        ("module", toJson modName.toString),
        ("scope", toJson scope),
        ("constants", toJson data.constNames.size)
      ]).compress)
      for name in data.constNames do
        constants := constants + 1
        match env.find? name with
        | none =>
          liftIO <| IO.println ("DECLAX_UNRESOLVED " ++ (Json.mkObj [
            ("module", toJson modName.toString),
            ("name", toJson name.toString)
          ]).compress)
        | some info =>
          let axioms <- liftCoreM (Lean.collectAxioms name)
          liftIO <| IO.println ("DECLAX_CONST " ++ (Json.mkObj [
            ("module", toJson modName.toString),
            ("name", toJson name.toString),
            ("kind", toJson (declaxKind info)),
            ("internal", toJson name.isInternalDetail),
            ("instance", toJson (Meta.isInstanceCore env name)),
            ("axioms", toJson (axioms.map Name.toString))
          ]).compress)
  liftIO <| IO.println ("DECLAX_END " ++ (Json.mkObj [
    ("modules", toJson modules),
    ("constants", toJson constants)
  ]).compress)
"""


@dataclasses.dataclass(frozen=True)
class Constant:
    """One constant as the census reported it."""

    module: str
    name: str
    kind: str
    internal: bool
    instance: bool
    axioms: tuple[str, ...]

    @property
    def disallowed(self) -> tuple[str, ...]:
        return tuple(sorted(set(self.axioms) - ALLOWED_AXIOMS))


@dataclasses.dataclass
class CensusOutput:
    """The records parsed out of one census run."""

    modules: dict[str, tuple[str, int]] = dataclasses.field(default_factory=dict)
    constants: list[Constant] = dataclasses.field(default_factory=list)
    unresolved: list[tuple[str, str]] = dataclasses.field(default_factory=list)
    end: tuple[int, int] | None = None
    malformed: list[str] = dataclasses.field(default_factory=list)


@dataclasses.dataclass
class Evaluation:
    """What the census found, ready to print."""

    failures: list[str]
    summary: str
    witness: str | None


def parse_pin(text: str) -> list[str]:
    """The module names in ``artifacts/elaborated_modules.txt``.

    Each name becomes an ``import`` line of the generated file, so the shape
    is checked strictly rather than passed through: a line that is not a
    ``Derivation.*`` module name is refused by name.
    """
    names: list[str] = []
    seen: set[str] = set()
    for number, raw in enumerate(text.replace("\r\n", "\n").split("\n"), start=1):
        line = raw.strip()
        if not line:
            continue
        if not MODULE_NAME.fullmatch(line):
            raise ValueError(f"pin line {number} is not a Derivation module name: {raw!r}")
        if line in seen:
            raise ValueError(f"pin line {number} repeats module {line}")
        seen.add(line)
        names.append(line)
    if not names:
        raise ValueError("pin names no modules -- the enumeration is broken")
    return names


def render_census(modules: Sequence[str]) -> str:
    """The generated Lean census for the root plus ``modules``.

    ``ParkedAudit`` is imported last so its constants can be read for the
    witness line; it is not a ``Derivation`` module and so is never in scope.
    """
    for name in modules:
        if not MODULE_NAME.fullmatch(name):
            raise ValueError(f"not a Derivation module name: {name!r}")
    ordered = [ROOT_MODULE, *sorted(set(modules)), WITNESS_MODULE]
    imports = "\n".join(f"import {name}" for name in ordered)
    return (
        CENSUS_TEMPLATE.replace("@@IMPORTS@@", imports)
        .replace("@@ROOT@@", ROOT_MODULE)
        .replace("@@WITNESS@@", WITNESS_MODULE)
    )


def _as_str(value: object, field: str) -> str:
    if not isinstance(value, str):
        raise ValueError(f"field {field!r} is not a string")
    return value


def _as_bool(value: object, field: str) -> bool:
    if not isinstance(value, bool):
        raise ValueError(f"field {field!r} is not a boolean")
    return value


def _as_int(value: object, field: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise ValueError(f"field {field!r} is not an integer")
    return value


def _record(line: str, prefix: str) -> dict[str, object]:
    payload = json.loads(line[len(prefix):])
    if not isinstance(payload, dict):
        raise ValueError("record is not a JSON object")
    return payload


def parse_output(text: str) -> CensusOutput:
    """Parse the census records out of Lean's standard output.

    Lines that do not start with a census prefix are ignored (Lean may print
    other messages); a line that DOES start with one and cannot be parsed is
    kept as malformed, which the evaluation turns into a failure.
    """
    out = CensusOutput()
    for line in text.replace("\r\n", "\n").split("\n"):
        prefix = next((p for p in PREFIXES if line.startswith(p)), None)
        if prefix is None:
            continue
        try:
            rec = _record(line, prefix)
            if prefix == "DECLAX_MODULE ":
                module = _as_str(rec.get("module"), "module")
                if module in out.modules:
                    raise ValueError(f"module {module} reported twice")
                out.modules[module] = (
                    _as_str(rec.get("scope"), "scope"),
                    _as_int(rec.get("constants"), "constants"),
                )
            elif prefix == "DECLAX_CONST ":
                axioms = rec.get("axioms")
                if not isinstance(axioms, list) or not all(
                    isinstance(a, str) for a in axioms
                ):
                    raise ValueError("field 'axioms' is not a list of strings")
                kind = _as_str(rec.get("kind"), "kind")
                if kind not in KINDS:
                    raise ValueError(f"unknown kind {kind!r}")
                out.constants.append(
                    Constant(
                        module=_as_str(rec.get("module"), "module"),
                        name=_as_str(rec.get("name"), "name"),
                        kind=kind,
                        internal=_as_bool(rec.get("internal"), "internal"),
                        instance=_as_bool(rec.get("instance"), "instance"),
                        axioms=tuple(str(a) for a in axioms),
                    )
                )
            elif prefix == "DECLAX_UNRESOLVED ":
                out.unresolved.append(
                    (
                        _as_str(rec.get("module"), "module"),
                        _as_str(rec.get("name"), "name"),
                    )
                )
            else:
                if out.end is not None:
                    raise ValueError("end record reported twice")
                out.end = (
                    _as_int(rec.get("modules"), "modules"),
                    _as_int(rec.get("constants"), "constants"),
                )
        except ValueError as exc:
            out.malformed.append(f"{exc}: {line}")
    return out


def _kind_counts(constants: Sequence[Constant]) -> str:
    counts = Counter(c.kind for c in constants)
    return ", ".join(f"{kind} {counts[kind]}" for kind in KINDS)


def evaluate(out: CensusOutput, pinned: Sequence[str]) -> Evaluation:
    """Turn parsed records into failures, one summary line and the witness."""
    failures: list[str] = []
    allowed = sorted(ALLOWED_AXIOMS)
    for problem in out.malformed:
        failures.append(f"malformed census record ({problem})")
    if out.end is None:
        failures.append("census output has no end record -- the run was cut short")
    expected = {ROOT_MODULE, *pinned}
    sealed = {m for m, (scope, _) in out.modules.items() if scope == "sealed"}
    for module in sorted(expected - sealed):
        failures.append(
            f"{module} is in the pin (or is the root) but the census read no "
            "constants from it"
        )
    for module in sorted(sealed - expected):
        failures.append(
            f"{module} was read by the census but is not in "
            "artifacts/elaborated_modules.txt"
        )
    for module, (scope, _) in sorted(out.modules.items()):
        if scope not in ("sealed", "witness"):
            failures.append(f"{module} carries unknown scope {scope!r}")
    if WITNESS_MODULE not in out.modules:
        failures.append(f"{WITNESS_MODULE} was not read -- the witness is missing")
    per_module = Counter(c.module for c in out.constants)
    per_module.update(m for m, _ in out.unresolved)
    for module, (_, declared) in sorted(out.modules.items()):
        if per_module[module] != declared:
            failures.append(
                f"{module} declares {declared} constants but the census "
                f"reported {per_module[module]}"
            )
    for module in sorted(set(per_module) - set(out.modules)):
        failures.append(f"{module} has constant records but no module record")
    if out.end is not None:
        total = len(out.constants) + len(out.unresolved)
        if out.end != (len(out.modules), total):
            failures.append(
                f"end record counts {out.end} differ from the records read "
                f"({len(out.modules)} modules, {total} constants)"
            )
    for module, name in sorted(out.unresolved):
        failures.append(f"{module}: {name} is in constNames but cannot be resolved")

    in_scope = [c for c in out.constants if c.module in sealed]
    for c in sorted(in_scope, key=lambda c: (c.module, c.name)):
        if c.disallowed:
            failures.append(
                f"{c.module}: {c.name} ({c.kind}) depends on disallowed axioms "
                f"{list(c.disallowed)} [all: {', '.join(c.axioms)}]"
            )

    instances = sum(1 for c in in_scope if c.instance)
    internal = sum(1 for c in in_scope if c.internal)
    counts = (
        f"{len(sealed)} Derivation modules, {len(in_scope)} constants "
        f"({_kind_counts(in_scope)}; {instances} instances, "
        f"{internal} internal details)"
    )
    if failures:
        bad = sum(1 for c in in_scope if c.disallowed)
        summary = (
            f"declaration axiom census FAILED: {counts}; constants outside "
            f"{allowed}: {bad}"
        )
    else:
        summary = f"declaration axiom census clean: {counts}, axioms within {allowed}"

    witness: str | None = None
    if WITNESS_MODULE in out.modules:
        read = [c for c in out.constants if c.module == WITNESS_MODULE]
        outside = sorted((c for c in read if c.disallowed), key=lambda c: c.name)
        listed = "; ".join(
            f"{c.name} ({c.kind}) [{', '.join(c.axioms)}]" for c in outside
        )
        witness = (
            f"witness (informational, outside the census by module): "
            f"{WITNESS_MODULE} adds {len(read)} constants, {len(outside)} "
            f"outside {allowed}" + (f": {listed}" if listed else "")
        )
    return Evaluation(failures=failures, summary=summary, witness=witness)


def temp_dir_outside(path: Path, forbidden: Sequence[Path]) -> None:
    """Refuse a census directory inside the repository or the Lean package."""
    resolved = path.resolve()
    for root in forbidden:
        if resolved.is_relative_to(root.resolve()):
            raise ValueError(
                f"census directory {resolved} is inside {root.resolve()}; "
                "set TMP/TEMP to a directory outside the repository"
            )


def run_lean(lean_dir: Path, census: str, timeout: int) -> tuple[int, str]:
    """Write ``census`` outside the repository and run it with ``lake env lean``."""
    lake = shutil.which("lake")
    if lake is None:
        raise RuntimeError("lake is not on PATH")
    with tempfile.TemporaryDirectory(prefix="declax-") as tmp:
        temp_dir_outside(Path(tmp), [REPO, lean_dir.parent])
        census_path = Path(tmp) / CENSUS_FILE_NAME
        census_path.write_bytes(census.encode("utf-8"))
        proc = subprocess.run(
            [lake, "env", "lean", str(census_path)],
            cwd=lean_dir,
            capture_output=True,
            timeout=timeout,
        )
    stdout = proc.stdout.decode("utf-8")
    stderr = proc.stderr.decode("utf-8", errors="replace")
    return proc.returncode, stdout + ("\n" + stderr if stderr else "")


Runner = Callable[[Path, str, int], tuple[int, str]]


def main(argv: Sequence[str] | None = None, runner: Runner = run_lean) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument(
        "--lean-dir",
        type=Path,
        default=REPO / "lean4",
        help="built Lean package to run `lake env lean` from (default: lean4)",
    )
    parser.add_argument(
        "--pin",
        type=Path,
        default=None,
        help="module pin (default: <lean-dir>/../artifacts/elaborated_modules.txt)",
    )
    parser.add_argument(
        "--raw-out",
        type=Path,
        default=None,
        help="also save Lean's raw census output to this file",
    )
    parser.add_argument(
        "--print-census",
        action="store_true",
        help="print the generated census file and exit without running Lean",
    )
    parser.add_argument("--timeout", type=int, default=DEFAULT_TIMEOUT)
    args = parser.parse_args(argv)

    lean_dir: Path = args.lean_dir.resolve()
    pin_path: Path = (
        args.pin if args.pin is not None
        else lean_dir.parent / "artifacts" / "elaborated_modules.txt"
    )
    try:
        pinned = parse_pin(pin_path.read_bytes().decode("utf-8"))
    except (OSError, ValueError) as exc:
        print(f"FAIL: cannot read module pin {pin_path}: {exc}")
        return 1
    census = render_census(pinned)
    if args.print_census:
        sys.stdout.write(census)
        return 0
    if not (lean_dir / "lakefile.toml").is_file():
        print(f"FAIL: {lean_dir} is not the Lean package (no lakefile.toml)")
        return 1
    try:
        code, output = runner(lean_dir, census, args.timeout)
    except (OSError, RuntimeError, ValueError, subprocess.TimeoutExpired) as exc:
        print(f"FAIL: census did not run: {exc}")
        return 1
    if args.raw_out is not None:
        args.raw_out.write_bytes(output.encode("utf-8"))
    if code != 0:
        tail = "\n".join(output.strip().splitlines()[-20:])
        print(f"FAIL: `lake env lean` exited {code}; is the package built?\n{tail}")
        return 1
    result = evaluate(parse_output(output), pinned)
    for failure in result.failures:
        print(f"FAIL: {failure}")
    print(result.summary)
    if result.witness is not None:
        print(result.witness)
    return 1 if result.failures else 0


if __name__ == "__main__":
    sys.exit(main())
