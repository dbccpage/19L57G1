"""Generate the Lean build order in ``docs/lean_build_order.md`` from the lakefiles.

A fresh clone has no build products.  Every research package that requires
the sealed package through a path builds the sealed modules it imports into
the shared ``lean4/.lake/``, and several research packages require one
another, so the order in which they are first built matters.  This script
reads that order from the require graph and writes it, with the exact
command for every package, between two marker lines of the page.  Nothing
outside the markers is changed, except that ``--write`` writes LF line
endings, which is what the git index holds.

Population: every ``lakefile.toml`` and ``lakefile.lean`` in the git index.
Their bytes are read from the working tree, so an edited lakefile shows up
before it is staged.  A require is either a ``[[require]]`` table with
exactly ``name`` and ``path``, or a ``require <name> from "<path>"`` line.
Any other require form, a path that holds no tracked lakefile, a require
name that differs from the required package's own name, and a cycle are
errors rather than rows, so the page cannot silently drop an edge.

Order: the base packages (required by others, requiring nothing) come first,
alone.  Then, for each group of packages joined by research-to-research
requires, its longest require chain one package at a time, then the rest of
that group by depth.  Then every package that requires only a base package,
then the packages that require nothing.  A package's depth is one more than
the deepest package it requires.

Two tables are recorded by hand, because no lakefile says them, and each
entry is checked against the tree: ``DUPLICATE_PACKAGE_DIRS`` (a Lake
package declared twice; which directory is the build entry) and ``SPECIAL``
(a package whose build needs a tree script).  A lakefile source directory
that holds no tracked file must have a ``SPECIAL`` entry that stages it.

The page is derived from the lakefiles, not replayed: ``--check`` compares
text and builds nothing.

``--check`` exits 1 and names what differs; ``--write`` rewrites the page.

AuthorityEffect: None.
"""

