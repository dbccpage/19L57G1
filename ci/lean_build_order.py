@dataclass(frozen=True)
class Package:
    directory: str
    lakefile: str
    name: str
    requires: tuple[tuple[str, str], ...]  # (require name, target directory)
    roots: tuple[str, ...]
    src_dirs: tuple[str, ...]  # package-relative, normalised; "." is the package itself


@dataclass(frozen=True)
class Graph:
    packages: Mapping[str, Package]  # build entries only
    skipped: Mapping[str, str]  # duplicate directory -> build entry
    stage: Mapping[str, int]
    base: tuple[str, ...]
    groups: tuple[tuple[tuple[str, ...], tuple[str, ...]], ...]  # (chain, rest)
    leaves: tuple[str, ...]
    standalone: tuple[str, ...]
    bare_dirs: Mapping[str, tuple[str, ...]]  # toolchain but no lakefile -> .lean files
    toolchains: Mapping[str, str | None]  # build directory -> pinned toolchain
    special: Mapping[str, Special]


def _git(repo: Path, *args: str) -> bytes:
    result = subprocess.run(["git", *args], cwd=repo, capture_output=True, check=False)
    if result.returncode != 0:
        reason = result.stderr.decode("utf-8", "replace").strip()
        raise ValueError(f"git {' '.join(args)} failed: {reason}")
    return result.stdout


def tracked_files(repo: Path) -> list[str]:
    """Every path in the git index, sorted."""
    raw = _git(repo, "ls-files", "-z")
    return sorted(p for p in raw.decode("utf-8").split("\0") if p)


def strip_lean_comments(text: str) -> str:
    """``text`` with Lean line and (nested) block comments blanked, strings kept."""
    out: list[str] = []
    i, depth, n = 0, 0, len(text)
    while i < n:
        two = text[i:i + 2]
        if depth:
            if two == "/-":
                depth, i = depth + 1, i + 2
            elif two == "-/":
                depth, i = depth - 1, i + 2
            else:
                out.append("\n" if text[i] == "\n" else " ")
                i += 1
            continue
        if two == "/-":
            depth, i = 1, i + 2
        elif two == "--":
            while i < n and text[i] != "\n":
                i += 1
        elif text[i] == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        else:
            out.append(text[i])
            i += 1
    if depth:
        raise ValueError("unterminated block comment")
    return "".join(out)


_NAME = r"(?:«[^»\n]+»|[A-Za-z_][A-Za-z0-9_'.]*)"
_DSL_PACKAGE = re.compile(rf"^package\s+({_NAME})", re.M)
_DSL_REQUIRE_LINE = re.compile(r"^[ \t]*require\b.*$", re.M)
_DSL_REQUIRE = re.compile(rf'^[ \t]*require[ \t]+("[^"\n]+"|{_NAME})[ \t]+from[ \t]+"([^"\n]+)"[ \t]*$')
_DSL_HEADER = re.compile(rf"^(package|lean_lib)[ \t]+({_NAME})(.*)$")
_DSL_SRC_DIR = re.compile(r'\bsrcDir\s*:=\s*"([^"\n]*)"')
_DSL_ROOTS = re.compile(r"\broots\s*:=\s*#\[([^\]]*)\]")
_DSL_ROOT_NAME = re.compile(r"`([^\s,`\]]+)")


def _unquote(name: str) -> str:
    if name.startswith('"') or name.startswith("«"):
        return name[1:-1]
    return name


def _norm_src(src: str | None) -> str:
    return posixpath.normpath(src) if src else "."


def parse_lakefile_lean(text: str) -> tuple[str, list[tuple[str, str]], list[str], list[str]]:
    """``(package name, [(require name, path)], roots, source dirs)`` of a Lean lakefile."""
    body = strip_lean_comments(text)
    package = _DSL_PACKAGE.search(body)
    if package is None:
        raise ValueError("no `package` declaration")
    requires: list[tuple[str, str]] = []
    for line in _DSL_REQUIRE_LINE.findall(body):
        match = _DSL_REQUIRE.match(line)
        if match is None:
            raise ValueError(f"unsupported require form: {line.strip()!r}")
        requires.append((_unquote(match.group(1)), match.group(2)))
    # A declaration's body is the rest of its header line plus the indented or
    # blank lines under it; comments are already blanked.  Any other line at
    # column zero (an attribute, another kind of declaration) ends the body.
    blocks: list[tuple[str, str, list[str]]] = []
    for line in body.split("\n"):
        header = _DSL_HEADER.match(line)
        if header:
            blocks.append((header.group(1), header.group(2), [header.group(3)]))
        elif line[:1].isspace() or not line.strip():
            if blocks:
                blocks[-1][2].append(line)
        else:
            blocks.append(("", "", []))
    package_src = "."
    roots: list[str] = []
    src_dirs: list[str] = []
    for kind, name, lines in blocks:
        text_of_block = "\n".join(lines)
        src = _DSL_SRC_DIR.search(text_of_block)
        if kind == "package":
            package_src = _norm_src(src.group(1) if src else None)
        elif kind == "lean_lib":
            lib_src = _norm_src(posixpath.join(package_src, src.group(1)) if src else package_src)
            src_dirs.append(lib_src)
            found = _DSL_ROOTS.search(text_of_block)
            roots.extend(_DSL_ROOT_NAME.findall(found.group(1)) if found else [_unquote(name)])
    return _unquote(package.group(1)), requires, roots, src_dirs


def parse_lakefile_toml(text: str) -> tuple[str, list[tuple[str, str]], list[str], list[str]]:
    """``(package name, [(require name, path)], roots, source dirs)`` of a TOML lakefile."""
    data = tomllib.loads(text)
    name = data.get("name")
    if not isinstance(name, str):
        raise ValueError("no string `name`")
    requires: list[tuple[str, str]] = []
    for require in data.get("require", []):
        if not isinstance(require, dict) or set(require) != {"name", "path"}:
            fields = sorted(require) if isinstance(require, dict) else require
            raise ValueError(f"unsupported require form: {fields!r}; only name and path")
        requires.append((str(require["name"]), str(require["path"])))
    package_src = _norm_src(data.get("srcDir"))
    roots: list[str] = []
    src_dirs: list[str] = []
    for lib in data.get("lean_lib", []):
        lib_name = str(lib["name"])
        lib_src = lib.get("srcDir")
        src_dirs.append(_norm_src(posixpath.join(package_src, lib_src) if lib_src else package_src))
        roots.extend(str(r) for r in lib.get("roots", [lib_name]))
    return name, requires, roots, src_dirs


def read_packages(repo: Path, files: Sequence[str]) -> dict[str, Package]:
    """Every tracked lakefile, parsed, keyed by its directory."""
    packages: dict[str, Package] = {}
    for rel in files:
        base = posixpath.basename(rel)
        if base not in LAKEFILES:
            continue
        directory = posixpath.dirname(rel) or "."
        if directory in packages:
            raise ValueError(f"{directory} holds both lakefile.toml and lakefile.lean")
        path = repo / rel
        if not path.is_file():
            raise ValueError(f"{rel} is tracked but missing from the working tree")
        text = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
        try:
            parsed = (parse_lakefile_toml if base.endswith(".toml") else parse_lakefile_lean)(text)
        except (ValueError, tomllib.TOMLDecodeError, KeyError) as exc:
            raise ValueError(f"{rel}: {exc}") from exc
        name, requires, roots, src_dirs = parsed
        targets = tuple(
            (req, posixpath.normpath(posixpath.join(directory, target))) for req, target in requires
        )
        packages[directory] = Package(directory, rel, name, targets, tuple(roots), tuple(src_dirs))
    return packages


def _module_file(package: Package, module: str, tracked: set[str]) -> str | None:
    tail = module.replace(".", "/") + ".lean"
    for src in package.src_dirs or (".",):
        candidate = posixpath.normpath(posixpath.join(package.directory, src, tail))
        if candidate in tracked:
            return candidate
    return None


def check_records(
    packages: Mapping[str, Package],
    files: Sequence[str],
    special: Mapping[str, Special],
    duplicates: Mapping[str, str],
) -> None:
    """Raise ValueError unless the hand-recorded tables agree with the tree."""
    tracked = set(files)
    by_name: dict[str, list[str]] = {}
    for directory, package in packages.items():
        by_name.setdefault(package.name, []).append(directory)
    for name, dirs in sorted(by_name.items()):
        if len(dirs) > 1:
            entries = [d for d in dirs if d not in duplicates]
            if len(entries) != 1:
                raise ValueError(
                    f"Lake package {name!r} is declared by {', '.join(sorted(dirs))}; record "
                    "every directory but the build entry in DUPLICATE_PACKAGE_DIRS"
                )
    for skipped, entry in duplicates.items():
        if skipped not in packages or entry not in packages:
            raise ValueError(f"DUPLICATE_PACKAGE_DIRS entry {skipped} -> {entry} names a "
                             "directory with no tracked lakefile")
        if entry in duplicates or packages[skipped].name != packages[entry].name:
            raise ValueError(f"DUPLICATE_PACKAGE_DIRS entry {skipped} -> {entry} does not "
                             "pair two declarations of one package with one build entry")
    for directory, record in special.items():
        if directory not in packages or directory in duplicates:
            raise ValueError(f"SPECIAL entry {directory} is not a build entry with a tracked lakefile")
        script = posixpath.join(record.cwd, record.argv[1]) if len(record.argv) > 1 else ""
        if record.argv[0] != "python" or script not in tracked:
            raise ValueError(f"SPECIAL entry {directory}: `{' '.join(record.argv)}` does not run "
                             f"a tracked script in {record.cwd}")
        package = packages[directory]
        if record.stages is not None:
            staged = posixpath.normpath(record.stages)
            prefix = posixpath.join(directory, staged) + "/"
            if staged not in package.src_dirs or any(f.startswith(prefix) for f in tracked):
                raise ValueError(f"SPECIAL entry {directory} stages {record.stages}/, which is "
                                 "not an untracked source directory of its lakefile")
        for module in record.not_roots:
            if module in package.roots or _module_file(package, module, tracked) is None:
                raise ValueError(f"SPECIAL entry {directory}: {module} is a root of the lakefile "
                                 "or not a tracked module of the package")
    for directory, package in packages.items():
        if directory in duplicates:
            continue
        for src in package.src_dirs:
            if src == ".":
                continue
            prefix = posixpath.join(directory, src) + "/"
            if not any(f.startswith(prefix) for f in tracked):
                stager = special.get(directory)
                if stager is None or stager.stages is None or posixpath.normpath(stager.stages) != src:
                    raise ValueError(
                        f"{package.lakefile} compiles {src}/, which holds no tracked file; add a "
                        "SPECIAL entry naming the tree script that stages it"
                    )


def build_graph(
    repo: Path,
    special: Mapping[str, Special] | None = None,
    duplicates: Mapping[str, str] | None = None,
) -> Graph:
    """The require graph of every tracked lakefile, ordered for a fresh build.

    ``special`` and ``duplicates`` default to the module's recorded tables.
    """
    special = SPECIAL if special is None else special
    duplicates = DUPLICATE_PACKAGE_DIRS if duplicates is None else duplicates
    files = tracked_files(repo)
    everything = read_packages(repo, files)
    check_records(everything, files, special, duplicates)
    for directory, package in sorted(everything.items()):
        for req, target in package.requires:
            if target not in everything:
                raise ValueError(f"{package.lakefile}: require {req!r} points at {target}, "
                                 "which holds no tracked lakefile")
            if everything[target].name != req:
                raise ValueError(f"{package.lakefile}: require {req!r} points at {target}, whose "
                                 f"package is named {everything[target].name!r}")
            if target in duplicates and directory not in duplicates:
                raise ValueError(f"{package.lakefile}: require {req!r} points at {target}, which "
                                 f"DUPLICATE_PACKAGE_DIRS says is not a build entry")
    packages = {d: p for d, p in everything.items() if d not in duplicates}

    stage: dict[str, int] = {}
    visiting: list[str] = []

    def depth(directory: str) -> int:
        if directory in stage:
            return stage[directory]
        if directory in visiting:
            cycle = visiting[visiting.index(directory):] + [directory]
            raise ValueError("require cycle: " + " -> ".join(cycle))
        visiting.append(directory)
        targets = [t for _, t in packages[directory].requires]
        stage[directory] = 1 + max((depth(t) for t in targets), default=-1)
        visiting.pop()
        return stage[directory]

    for directory in sorted(packages):
        depth(directory)

    required = {t for p in packages.values() for _, t in p.requires}
    base = tuple(sorted(d for d in packages if stage[d] == 0 and d in required))
    inner = {
        (d, t) for d, p in packages.items() for _, t in p.requires if t not in base
    }
    chained = {d for edge in inner for d in edge}
    neighbours: dict[str, set[str]] = {d: set() for d in chained}
    for a, b in inner:
        neighbours[a].add(b)
        neighbours[b].add(a)
    groups: list[tuple[tuple[str, ...], tuple[str, ...]]] = []
    unseen = set(chained)
    while unseen:
        start = min(unseen)
        component, frontier = {start}, [start]
        while frontier:
            for other in neighbours[frontier.pop()]:
                if other not in component:
                    component.add(other)
                    frontier.append(other)
        unseen -= component
        top = min(component, key=lambda d: (-stage[d], d))
        chain = [top]
        while True:
            below = [t for _, t in packages[chain[-1]].requires if t in component]
            if not below:
                break
            chain.append(min(below, key=lambda d: (-stage[d], d)))
        chain.reverse()
        rest = tuple(sorted(component - set(chain), key=lambda d: (stage[d], d)))
        groups.append((tuple(chain), rest))
    groups.sort(key=lambda g: (-len(g[0]), g[0][0]))
    placed = set(base) | chained
    leaves = tuple(sorted(d for d in packages if d not in placed and stage[d] > 0))
    standalone = tuple(sorted(d for d in packages if d not in placed and stage[d] == 0))

    tracked = set(files)
    lake_dirs = set(everything)
    bare: dict[str, list[str]] = {}
    for rel in files:
        if posixpath.basename(rel) == TOOLCHAIN:
            directory = posixpath.dirname(rel) or "."
            if directory not in lake_dirs:
                bare[directory] = sorted(
                    posixpath.basename(f) for f in tracked
                    if posixpath.dirname(f) == directory and f.endswith(".lean")
                )
    toolchains: dict[str, str | None] = {}
    for directory in sorted(set(packages) | set(bare)):
        pin = posixpath.join(directory, TOOLCHAIN) if directory != "." else TOOLCHAIN
        toolchains[directory] = (
            (repo / pin).read_bytes().decode("utf-8").strip() if pin in tracked else None
        )
    return Graph(
        packages=packages,
        skipped=dict(duplicates),
        stage=stage,
        base=base,
        groups=tuple(groups),
        leaves=leaves,
        standalone=standalone,
        bare_dirs={d: tuple(v) for d, v in sorted(bare.items())},
        toolchains=toolchains,
        special=dict(special),
    )


def sequence(graph: Graph) -> list[str]:
    """Every build entry in the order the page gives it."""
    order = list(graph.base)
    for chain, rest in graph.groups:
        order += [*chain, *rest]
    return order + list(graph.leaves) + list(graph.standalone)


def closure(graph: Graph, directory: str) -> list[str]:
    """``directory`` and every package it requires, directly or not."""
    seen, frontier = [directory], [directory]
    while frontier:
        for _, target in graph.packages[frontier.pop()].requires:
            if target not in seen:
                seen.append(target)
                frontier.append(target)
    return seen


def shared_roots(graph: Graph) -> list[tuple[str, str, tuple[str, ...]]]:
    """``(package, module, supplying packages)`` for each root module a closure holds twice."""
    rows: list[tuple[str, str, tuple[str, ...]]] = []
    for directory in sequence(graph):
        suppliers: dict[str, list[str]] = {}
        for member in closure(graph, directory):
            for module in set(graph.packages[member].roots):
                suppliers.setdefault(module, []).append(graph.packages[member].name)
        for module, names in sorted(suppliers.items()):
            if len(names) > 1:
                rows.append((directory, module, tuple(sorted(names))))
    return rows


def _ps(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _call(directory: str, argv: Sequence[str]) -> str:
    args = ", ".join(_ps(a) for a in argv[1:])
    return f"Invoke-InDir {_ps(directory)} {_ps(argv[0])} @({args})"


def _commands(graph: Graph, directory: str) -> list[str]:
    record = graph.special.get(directory)
    lines: list[str] = []
    if record is None or not record.replaces_build:
        lines.append(_call(directory, ("lake", "build")))
    if record is not None:
        lines.append(_call(record.cwd, record.argv))
    return lines


def _code(value: str) -> str:
    return f"`{value}`"


def render_block(graph: Graph) -> str:
    """The generated block, marker lines included, LF-terminated."""
    order = sequence(graph)
    step = {d: i + 1 for i, d in enumerate(order)}
    lines = [BEGIN, "", "### Build sequence", ""]
    lines.append(
        f"{len(order)} build entries: {len(graph.base)} base, "
        f"{sum(len(c) + len(r) for c, r in graph.groups)} in "
        f"{len(graph.groups)} require group(s), {len(graph.leaves)} requiring only a base "
        f"package, {len(graph.standalone)} requiring nothing.  Run the block from the "
        "repository root.  Each command throws when it fails, so a run of the block saved as "
        "a script stops at the first failure."
    )
    lines += ["", "```powershell", "$env:PYTHONUTF8 = '1'",
              "function Invoke-InDir([string]$Dir, [string]$Exe, [string[]]$Arguments) {",
              "  Push-Location $Dir",
              "  try {",
              "    & $Exe @Arguments",
              "    if ($LASTEXITCODE -ne 0) { throw \"failed in ${Dir}: $Exe $Arguments\" }",
              "  } finally {",
              "    Pop-Location",
              "  }",
              "}"]
    lines.append("# Base package(s), alone, before anything that requires them.")
    for directory in graph.base:
        lines += _commands(graph, directory)
    for number, (chain, rest) in enumerate(graph.groups, start=1):
        names = " -> ".join(graph.packages[d].name for d in chain)
        lines.append(f"# Require group {number}: its longest chain, one at a time: {names}.")
        for directory in chain:
            lines += _commands(graph, directory)
        if rest:
            lines.append(f"# Require group {number}: the rest, after what each one requires.")
            for directory in rest:
                lines += _commands(graph, directory)
    lines.append("# Packages that require only a base package, one at a time, any order.")
    for directory in graph.leaves:
        lines += _commands(graph, directory)
    lines.append("# Packages that require nothing; they do not read lean4/.lake/.")
    for directory in graph.standalone:
        lines += _commands(graph, directory)
    if graph.bare_dirs:
        lines.append("# Directories with a lean-toolchain and no lakefile: one file at a time.")
        for directory, sources in graph.bare_dirs.items():
            for source in sources:
                lines.append(_call(directory, ("lean", source)))
    lines += ["```", ""]

    lines += ["### Every build entry", "",
              f"| step | directory | Lake name | requires | depth | builds into `{SEALED_DIR}/.lake/` "
              "| script step |",
              "|---|---|---|---|---|---|---|"]
    for directory in order:
        package = graph.packages[directory]
        requires = ", ".join(_code(r) for r, _ in package.requires) or "none"
        shares = "yes" if SEALED_DIR in closure(graph, directory) else "no"
        record = graph.special.get(directory)
        if record is None:
            first = "none"
        else:
            label = "instead of `lake build`" if record.replaces_build else "after `lake build`"
            first = f"`{' '.join(record.argv)}` in `{record.cwd}`, {label}: {record.why}"
            if record.not_roots:
                first += " (" + ", ".join(_code(m) for m in record.not_roots) + ")"
        lines.append(
            f"| {step[directory]} | {_code(directory)} | {_code(package.name)} | {requires} | "
            f"{graph.stage[directory]} | {shares} | {first} |"
        )
    lines.append("")
    if graph.skipped:
        lines += ["Lakefiles that are not build entries, because the same Lake package is "
                  "declared in another directory:", ""]
        for skipped, entry in sorted(graph.skipped.items()):
            lines.append(f"- {_code(skipped)}: build {_code(entry)} instead.")
        lines.append("")

    pins: dict[str | None, list[str]] = {}
    for directory, pin in graph.toolchains.items():
        pins.setdefault(pin, []).append(directory)
    lines += ["### Toolchain pins", ""]
    for pin, dirs in sorted(pins.items(), key=lambda item: (item[0] is None, item[0] or "")):
        label = _code(pin) if pin is not None else "no `lean-toolchain` in the directory"
        lines.append(f"- {label}: {len(dirs)} build director{'y' if len(dirs) == 1 else 'ies'}.")
        if pin is None or len(pins) > 1:
            lines += [f"  - {_code(d)}" for d in dirs]
    lines.append("")

    rows = shared_roots(graph)
    lines += ["### Root modules supplied more than once in one require closure", ""]
    if rows:
        lines += ["| directory | module | supplied by |", "|---|---|---|"]
        for directory, module, suppliers in rows:
            lines.append(f"| {_code(directory)} | {_code(module)} | "
                         + ", ".join(_code(n) for n in suppliers) + " |")
    else:
        lines.append("None.")
    lines += ["", END]
    return "\n".join(lines) + "\n"


def splice(text: str, block: str) -> str:
    """Replace the marked region of ``text`` (LF-normalised) with ``block``."""
    lines = text.replace("\r\n", "\n").splitlines(keepends=True)
    begins = [i for i, line in enumerate(lines) if line.rstrip("\n") == BEGIN]
    ends = [i for i, line in enumerate(lines) if line.rstrip("\n") == END]
    if len(begins) != 1 or len(ends) != 1 or begins[0] > ends[0]:
        raise ValueError(
            f"{PAGE_REL} must contain exactly one '{BEGIN}' line followed by "
            f"exactly one '{END}' line (found {len(begins)} and {len(ends)})"
        )
    return "".join(lines[:begins[0]]) + block + "".join(lines[ends[0] + 1:])


def expected_page(
    repo: Path,
    current: str,
    special: Mapping[str, Special] | None = None,
    duplicates: Mapping[str, str] | None = None,
) -> str:
    """``current`` with its marked region regenerated."""
    return splice(current, render_block(build_graph(repo, special, duplicates)))


def problems(
    repo: Path,
    special: Mapping[str, Special] | None = None,
    duplicates: Mapping[str, str] | None = None,
) -> list[str]:
    """Empty when the page is current; otherwise lines naming the drift."""
    target = repo / PAGE_REL
    if not target.is_file():
        return [f"{PAGE_REL} is missing"]
    current = target.read_bytes().decode("utf-8").replace("\r\n", "\n")
    try:
        expected = expected_page(repo, current, special, duplicates)
    except ValueError as exc:
        return [str(exc)]
    if current == expected:
        return []
    report = [f"{PAGE_REL} is stale; regenerate it with: {REGENERATE}"]
    report += difflib.unified_diff(
        current.splitlines(), expected.splitlines(),
        f"{PAGE_REL} (committed)", f"{PAGE_REL} (generated)", lineterm="", n=0,
    )
    return report


def main(argv: Sequence[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="backslashreplace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="exit 1 if the page is stale")
    mode.add_argument("--write", action="store_true", help="rewrite the page in place")
    args = parser.parse_args(argv)
    try:
        if args.check:
            found = problems(REPO)
            print("\n".join(found) if found else f"{PAGE_REL} is current")
            return 1 if found else 0
        target = REPO / PAGE_REL
        before = target.read_bytes()
        after = expected_page(REPO, before.decode("utf-8").replace("\r\n", "\n")).encode("utf-8")
    except (ValueError, OSError) as exc:
        print(exc)
        return 1
    if before == after:
        print(f"{PAGE_REL} already current")
    else:
        target.write_bytes(after)
        print(f"wrote {PAGE_REL}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
