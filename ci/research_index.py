"""Generate the list of research trees in ``research/README.md``.

The list of research trees, and which of them the written contract runs as
gate 11, was typed by hand, and trees went missing from it.  This script
derives both from the git index and writes them as a two-column table
between two marker lines.  Nothing outside the markers is changed, except
that ``--write`` writes LF line endings, which is what the git index holds.

Population: every top-level directory under ``research/`` that holds a file
in the git index, except names beginning with ``_`` (templates) and the
directories in ``NOT_TREES``.

Gate 11: ``workflow (gate 11)`` when ``research/<tree>`` appears as a whole
path segment anywhere in the ``research:`` job of the workflow file as the
index holds it -- in a command, a working directory, or a comment; otherwise
``local receipt only``.  Comments count because the workflow registers the
second derivation's rungs by naming ``research/second/`` in a comment.  This
is the reading ``research/estate_honesty/audit_estate.py`` uses, and
``tests/test_research_index.py`` checks that the two agree.

Only these two columns are committed, and they change only when a tree is
added, removed, or registered in the workflow, so work inside a tree never
makes the README stale.  The table carries no total: two branches that each
add a tree would both rewrite a total line, and git would merge them into a
wrong one.

``--show`` prints a longer table that is not committed: each tree's
``verify*.py`` entry points, where its ``test_*.py`` files are, its Lean
files and what checks them, and which other trees require it in a
``lakefile.toml`` or name one of its paths in a tracked JSON file (a
reference, not necessarily a pin).  It reads the working tree.

``--check`` exits 1 and names what differs; ``--write`` rewrites the file.

AuthorityEffect: None.
"""

from __future__ import annotations

import argparse
import difflib
import posixpath
import re
import subprocess
import sys
import tomllib
from collections.abc import Mapping, Sequence
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
README_REL = "research/README.md"
WORKFLOW_REL = ".github/workflows/verify.yml"
BEGIN = "<!-- generated by ci/research_index.py: begin -->"
END = "<!-- generated by ci/research_index.py: end -->"
HEADER = "| tree | gate 11 |"
RULE = "|---|---|"
WIRED = "workflow (gate 11)"
LOCAL = "local receipt only"
REGENERATE = "python ci/research_index.py --write"

# Top-level directories under research/ that are not trees.
NOT_TREES: Mapping[str, str] = {
    "e2e_tests": "a harness that runs other trees' test suites",
    "notes": "prose notes",
}

_JOB_HEADER = re.compile(r"^  ([A-Za-z0-9_-]+):\s*(#.*)?$")
_TREE_TOKEN = re.compile(r"(?<![A-Za-z0-9_])research/([A-Za-z0-9_-]+)(?![A-Za-z0-9_-])")
_LEAN_JOB_VERIFIER = re.compile(r"(?<![A-Za-z0-9_])research/([A-Za-z0-9_-]+)/verify_lean\.py\b")
_JSON_TREE_PATH = re.compile(rb"research/([A-Za-z0-9_-]+)(?=[/\"])")
_PATH_CONTINUES = frozenset(
    b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_./-"
)
_ROW_TREE = re.compile(r"^\|\s*`([^`]+)`\s*\|")


def _git(repo: Path, *args: str) -> bytes:
    result = subprocess.run(["git", *args], cwd=repo, capture_output=True, check=False)
    if result.returncode != 0:
        reason = result.stderr.decode("utf-8", "replace").strip()
        raise ValueError(f"git {' '.join(args)} failed: {reason}")
    return result.stdout


def tracked_research_files(repo: Path) -> list[str]:
    """Every path under ``research/`` in the git index, in git's order."""
    raw = _git(repo, "ls-files", "-z", "--", "research/")
    return [p for p in raw.decode("utf-8").split("\0") if p]


def group_trees(paths: Sequence[str]) -> dict[str, tuple[str, ...]]:
    """Each tree's tracked paths, relative to the tree root, keyed by name."""
    grouped: dict[str, list[str]] = {}
    for path in paths:
        parts = path.split("/", 2)
        if len(parts) < 3:
            continue
        name = parts[1]
        if name.startswith("_") or name in NOT_TREES:
            continue
        grouped.setdefault(name, []).append(parts[2])
    return {name: tuple(sorted(grouped[name])) for name in sorted(grouped)}


def workflow_text(repo: Path) -> str:
    """The workflow file as the git index holds it."""
    return _git(repo, "show", f":{WORKFLOW_REL}").decode("utf-8")


def job_lines(workflow: str, job: str, *, comments: bool) -> list[str]:
    """The lines of one job under ``jobs:``, with or without comment lines."""
    lines = workflow.replace("\r\n", "\n").split("\n")
    if "jobs:" not in lines:
        raise ValueError(f"{WORKFLOW_REL} has no top-level 'jobs:' line")
    current: str | None = None
    found = False
    body: list[str] = []
    for line in lines[lines.index("jobs:") + 1:]:
        if line and not line[0].isspace() and not line.startswith("#"):
            break
        header = _JOB_HEADER.match(line)
        if header:
            current = header.group(1)
            found = found or current == job
            continue
        if current == job and (comments or not line.lstrip().startswith("#")):
            body.append(line)
    if not found:
        raise ValueError(f"{WORKFLOW_REL} has no '{job}:' job")
    return body


def named_trees(lines: Sequence[str]) -> set[str]:
    """Every ``<tree>`` a line names as ``research/<tree>``, whole segment."""
    return {m.group(1) for line in lines for m in _TREE_TOKEN.finditer(line)}


def wired_trees(workflow: str) -> set[str]:
    """Trees named anywhere in the ``research:`` job, comments included."""
    return named_trees(job_lines(workflow, "research", comments=True))


def render_block(trees: Sequence[str], wired: set[str]) -> str:
    """The generated block, marker lines included, LF-terminated."""
    lines = [BEGIN, HEADER, RULE]
    lines += [f"| `{name}` | {WIRED if name in wired else LOCAL} |" for name in trees]
    lines.append(END)
    return "\n".join(lines) + "\n"


def splice(text: str, block: str) -> str:
    """Replace the marked region of ``text`` (LF-normalised) with ``block``."""
    lines = text.replace("\r\n", "\n").splitlines(keepends=True)
    begins = [i for i, line in enumerate(lines) if line.rstrip("\n") == BEGIN]
    ends = [i for i, line in enumerate(lines) if line.rstrip("\n") == END]
    if len(begins) != 1 or len(ends) != 1 or begins[0] > ends[0]:
        raise ValueError(
            f"{README_REL} must contain exactly one '{BEGIN}' line followed by "
            f"exactly one '{END}' line (found {len(begins)} and {len(ends)})"
        )
    return "".join(lines[:begins[0]]) + block + "".join(lines[ends[0] + 1:])


def expected_readme(repo: Path, current: str) -> str:
    """``current`` with its marked region regenerated."""
    trees = list(group_trees(tracked_research_files(repo)))
    return splice(current, render_block(trees, wired_trees(workflow_text(repo))))


def _table_trees(text: str) -> set[str]:
    inside, names = False, set()
    for line in text.split("\n"):
        if line == BEGIN:
            inside = True
        elif line == END:
            break
        elif inside and (match := _ROW_TREE.match(line)):
            names.add(match.group(1))
    return names


def problems(repo: Path) -> list[str]:
    """Empty when the README is current; otherwise lines naming the drift."""
    current = (repo / README_REL).read_bytes().decode("utf-8").replace("\r\n", "\n")
    try:
        expected = expected_readme(repo, current)
    except ValueError as exc:
        return [str(exc)]
    if current == expected:
        return []
    report = [f"{README_REL} is stale; regenerate it with: {REGENERATE}"]
    have, want = _table_trees(current), _table_trees(expected)
    if want - have:
        report.append("trees missing from the table: " + ", ".join(sorted(want - have)))
    if have - want:
        report.append("rows that are not tracked trees: " + ", ".join(sorted(have - want)))
    report += difflib.unified_diff(
        current.splitlines(), expected.splitlines(),
        f"{README_REL} (committed)", f"{README_REL} (generated)", lineterm="", n=0,
    )
    return report


# --show: an uncommitted, longer table for reading.

def _test_dirs(files: Sequence[str]) -> list[str]:
    dirs = {posixpath.dirname(f) for f in files if posixpath.basename(f).startswith("test_")
            and f.endswith(".py")}
    return sorted(f"{d}/" if d else "root" for d in dirs)


def _references(repo: Path, trees: Mapping[str, tuple[str, ...]]) -> dict[str, set[str]]:
    """For each tree, the other trees that require it or name one of its paths."""
    found: dict[str, set[str]] = {name: set() for name in trees}
    for owner, files in trees.items():
        for rel in files:
            base = posixpath.basename(rel)
            if base != "lakefile.toml" and not base.endswith(".json"):
                continue
            full = f"research/{owner}/{rel}"
            source = repo / full
            if not source.is_file():
                continue
            targets: list[str] = []
            if base == "lakefile.toml":
                for require in tomllib.loads(source.read_text(encoding="utf-8")).get("require", []):
                    joined = posixpath.normpath(
                        posixpath.join(posixpath.dirname(full), str(require.get("path", "")))
                    )
                    parts = joined.split("/")
                    if len(parts) > 1 and parts[0] == "research":
                        targets.append(parts[1])
            else:
                data = source.read_bytes()
                if b"research/" in data:
                    for match in _JSON_TREE_PATH.finditer(data):
                        at = match.start()
                        if at == 0 or data[at - 1] not in _PATH_CONTINUES:
                            targets.append(match.group(1).decode("ascii"))
            for tree in targets:
                if tree in found and tree != owner:
                    found[tree].add(owner)
    return found


def show(repo: Path) -> str:
    """The longer table ``--show`` prints."""
    trees = group_trees(tracked_research_files(repo))
    workflow = workflow_text(repo)
    wired = wired_trees(workflow)
    lean_job = {
        m.group(1)
        for line in job_lines(workflow, "lean", comments=False)
        for m in _LEAN_JOB_VERIFIER.finditer(line)
    }
    refs = _references(repo, trees)
    rows = ["| tree | gate 11 | entry points | tests | Lean | required or named by |",
            "|---|---|---|---|---|---|"]
    for name, files in trees.items():
        root = [f for f in files if "/" not in f]
        entry = [f for f in root if f.startswith("verify") and f.endswith(".py")]
        modules = [f for f in files if f.endswith(".lean") and posixpath.basename(f) != "lakefile.lean"]
        if not modules:
            lean = "none"
        elif name in lean_job:
            lean = f"{len(modules)}, workflow Lean job"
        else:
            checker = next((v for v in ("verify_lean.py", "verify.py") if v in root), None)
            lean = f"{len(modules)}, " + (f"local `{checker}`" if checker else "no verifier")
        cells = [
            f"`{name}`", WIRED if name in wired else LOCAL,
            ", ".join(f"`{e}`" for e in entry) or "none",
            ", ".join(d if d == "root" else f"`{d}`" for d in _test_dirs(files)) or "none",
            lean,
            ", ".join(f"`{r}`" for r in sorted(refs[name])) or "none",
        ]
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="backslashreplace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="exit 1 if the README is stale")
    mode.add_argument("--write", action="store_true", help="rewrite the README in place")
    mode.add_argument("--show", action="store_true", help="print the longer, uncommitted table")
    args = parser.parse_args(argv)
    try:
        if args.show:
            print(show(REPO), end="")
            return 0
        if args.check:
            found = problems(REPO)
            print("\n".join(found) if found else f"{README_REL} is current")
            return 1 if found else 0
        target = REPO / README_REL
        before = target.read_bytes()
        after = expected_readme(REPO, before.decode("utf-8").replace("\r\n", "\n")).encode("utf-8")
    except ValueError as exc:
        print(exc)
        return 1
    if before == after:
        print(f"{README_REL} already current")
    else:
        target.write_bytes(after)
        print(f"wrote {README_REL}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
