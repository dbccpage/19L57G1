"""Generate the research-tree index in ``research/README.md``.

The table of research trees and the lists of hand-copied verifier files in
that README were typed by hand, and they drifted.  This script derives both
from the git index and ``.github/workflows/verify.yml`` and writes them
between two marker lines.  Text outside the markers is kept as it is; the
only change ``--write`` makes to it is that line endings are written as LF,
which is what the git index holds.

Population: every top-level directory under ``research/`` that holds at
least one file listed by ``git ls-files`` (tracked or staged), except names
beginning with ``_``, which are templates.  Untracked files are never read.

Columns, all mechanical:

* gate 11 -- ``workflow (gate 11)`` when ``research/<tree>`` appears on a
  non-comment line of the ``research:`` job of the workflow file, ending at
  ``/`` or at a character that cannot continue a name (so ``second`` is not
  matched by ``second_stake``); otherwise ``local receipt only``.
* check entry points -- tracked ``verify*.py`` files at the tree root.
* tests -- ``tests/`` when tracked files sit under ``tests/``, else
  ``test_*.py`` when tracked ``test_*.py`` files sit at the tree root.
* Lean -- the count of tracked ``.lean`` files (``lakefile.lean`` is build
  configuration, not a module) and what builds them: the workflow ``lean:``
  job when a non-comment line of it invokes the tree's ``verify_lean.py``,
  else the tree's own ``verify_lean.py``, else its ``verify.py``.
* pinned or required by -- other trees whose tracked ``lakefile.toml`` or
  ``lakefile.lean`` requires a path resolving into this tree, or whose
  tracked ``.json`` files mention a path beginning ``research/<tree>/``.
  Nothing else (no Python imports, no prose) is read for this column.

``--check`` exits 1 and names what differs; ``--write`` rewrites the file.
``tests/test_research_index.py`` runs the check in the root suite, and
``research/estate_honesty/audit_estate.py`` parses the first two columns.

AuthorityEffect: None.
"""

from __future__ import annotations

import argparse
import difflib
import posixpath
import re
import subprocess
import sys
import tomllib
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
README_REL = "research/README.md"
WORKFLOW_REL = ".github/workflows/verify.yml"
BEGIN = "<!-- generated by ci/research_index.py: begin -->"
END = "<!-- generated by ci/research_index.py: end -->"
HEADER = (
    "| tree | gate 11 | check entry points | tests | Lean "
    "| pinned or required by |"
)
RULE = "|---|---|---|---|---|---|"
WIRED = "workflow (gate 11)"
LOCAL = "local receipt only"
COPY_FILES: tuple[str, ...] = (
    "verify_sources.py",
    "verify_pins.py",
    "verify_lean.py",
    "run.py",
    "verify.py",
)
REGENERATE = "python ci/research_index.py --write"

_JOB_HEADER = re.compile(r"^  ([A-Za-z0-9_-]+):\s*$")
_JSON_TREE_PATH = re.compile(rb"research/([A-Za-z0-9_.-]+)/")
_PATH_CONTINUES = frozenset(
    b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_./-"
)
_LEAN_BLOCK_COMMENT = re.compile(r"/-.*?-/", re.DOTALL)
_LEAN_LINE_COMMENT = re.compile(r"--[^\n]*")
_LEAN_REQUIRE = re.compile(r'^\s*require\b[^\n"]*?\bfrom\s+"([^"]+)"', re.MULTILINE)
_ROW_TREE = re.compile(r"^\|\s*`([^`]+)`\s*\|")


@dataclass(frozen=True)
class Row:
    """One generated table row."""

    name: str
    status: str
    entry_points: tuple[str, ...]
    tests: str
    lean: str
    dependents: tuple[str, ...]


def tracked_research_files(repo: Path) -> list[str]:
    """Every path under ``research/`` in the git index, sorted."""
    result = subprocess.run(
        ["git", "ls-files", "-z", "--", "research/"],
        cwd=repo,
        capture_output=True,
        check=True,
    )
    paths = {p for p in result.stdout.decode("utf-8").split("\0") if p}
    return sorted(paths)


def group_trees(paths: Sequence[str]) -> dict[str, tuple[str, ...]]:
    """Map each tree name to its tracked paths, relative to the tree root."""
    grouped: dict[str, set[str]] = {}
    for path in paths:
        parts = path.split("/", 2)
        if len(parts) < 3 or parts[0] != "research":
            continue
        name, rel = parts[1], parts[2]
        if not name or name.startswith("_") or not rel:
            continue
        grouped.setdefault(name, set()).add(rel)
    return {name: tuple(sorted(grouped[name])) for name in sorted(grouped)}


def job_lines(workflow: str, job: str) -> list[str]:
    """Non-comment lines of one job under ``jobs:`` in the workflow text."""
    lines = workflow.splitlines()
    if "jobs:" not in lines:
        raise ValueError(f"{WORKFLOW_REL} has no top-level 'jobs:' line")
    current: str | None = None
    found = False
    body: list[str] = []
    for line in lines[lines.index("jobs:") + 1:]:
        if line and not line[0].isspace() and not line.startswith("#"):
            break
        header = _JOB_HEADER.match(line)
        if header:
            current = header.group(1)
            found = found or current == job
            continue
        if current == job and not line.lstrip().startswith("#"):
            body.append(line)
    if not found:
        raise ValueError(f"{WORKFLOW_REL} has no '{job}:' job")
    return body


def mentions_tree(lines: Sequence[str], tree: str) -> bool:
    """True when some line names ``research/<tree>`` as a whole path segment."""
    pattern = re.compile(
        r"(?<![A-Za-z0-9_])research/" + re.escape(tree) + r"(?![A-Za-z0-9_.-])"
    )
    return any(pattern.search(line) for line in lines)


def invokes_verify_lean(lines: Sequence[str], tree: str) -> bool:
    """True when some line names ``research/<tree>/verify_lean.py``."""
    pattern = re.compile(
        r"(?<![A-Za-z0-9_])research/"
        + re.escape(tree)
        + r"/verify_lean\.py(?![A-Za-z0-9_.-])"
    )
    return any(pattern.search(line) for line in lines)


def toml_require_paths(text: str) -> list[str]:
    """The ``path`` of every ``[[require]]`` table in a ``lakefile.toml``."""
    data = tomllib.loads(text)
    paths: list[str] = []
    requires = data.get("require", [])
    if isinstance(requires, list):
        for require in requires:
            if isinstance(require, dict):
                path = require.get("path")
                if isinstance(path, str):
                    paths.append(path)
    return paths


def lean_require_paths(text: str) -> list[str]:
    """The local path of every ``require ... from "path"`` in a ``lakefile.lean``."""
    code = _LEAN_BLOCK_COMMENT.sub("", text)
    code = _LEAN_LINE_COMMENT.sub("", code)
    return _LEAN_REQUIRE.findall(code)


def _tree_of(path: str, names: Mapping[str, object]) -> str | None:
    parts = path.split("/")
    if len(parts) >= 2 and parts[0] == "research" and parts[1] in names:
        return parts[1]
    return None


def dependents(repo: Path, trees: Mapping[str, tuple[str, ...]]) -> dict[str, set[str]]:
    """For each tree, the other trees that require or pin a path inside it."""
    found: dict[str, set[str]] = {name: set() for name in trees}
    for owner, files in trees.items():
        for rel in files:
            full = f"research/{owner}/{rel}"
            source = repo / full
            if not source.is_file():
                continue
            base = posixpath.basename(rel)
            targets: list[str] = []
            if base in ("lakefile.toml", "lakefile.lean"):
                text = source.read_bytes().decode("utf-8")
                if base == "lakefile.toml":
                    try:
                        required = toml_require_paths(text)
                    except tomllib.TOMLDecodeError as exc:
                        raise ValueError(f"{full}: {exc}") from exc
                else:
                    required = lean_require_paths(text)
                for path in required:
                    joined = posixpath.join(
                        posixpath.dirname(full), path.replace("\\", "/")
                    )
                    tree = _tree_of(posixpath.normpath(joined), trees)
                    if tree is not None:
                        targets.append(tree)
            elif rel.endswith(".json"):
                data = source.read_bytes()
                if b"research/" in data:
                    # A leading lookbehind defeats the regex engine's literal
                    # prefix scan and costs ~30x, so the check is done here:
                    # the path must START at research/, not continue a longer one.
                    for match in _JSON_TREE_PATH.finditer(data):
                        at = match.start()
                        if at == 0 or data[at - 1] not in _PATH_CONTINUES:
                            targets.append(match.group(1).decode("ascii"))
            for tree in targets:
                if tree in found and tree != owner:
                    found[tree].add(owner)
    return found


def _code_list(items: Sequence[str]) -> str:
    return ", ".join(f"`{item}`" for item in items) if items else "none"


def _root_files(files: Sequence[str]) -> set[str]:
    return {f for f in files if "/" not in f}


def build_rows(repo: Path, trees: Mapping[str, tuple[str, ...]]) -> list[Row]:
    """Every row of the table, in tree-name order."""
    workflow = (repo / WORKFLOW_REL).read_bytes().decode("utf-8")
    research_job = job_lines(workflow, "research")
    lean_job = job_lines(workflow, "lean")
    pinned_by = dependents(repo, trees)
    rows: list[Row] = []
    for name, files in trees.items():
        root = _root_files(files)
        entry = tuple(
            sorted(f for f in root if f.startswith("verify") and f.endswith(".py"))
        )
        if any(f.startswith("tests/") for f in files):
            tests = "tests/"
        elif any(f.startswith("test_") and f.endswith(".py") for f in root):
            tests = "test_*.py"
        else:
            tests = "none"
        modules = [
            f for f in files
            if f.endswith(".lean") and posixpath.basename(f) != "lakefile.lean"
        ]
        if not modules:
            lean = "none"
        else:
            if invokes_verify_lean(lean_job, name):
                how = "workflow Lean job"
            elif "verify_lean.py" in root:
                how = "local receipt (`verify_lean.py`)"
            elif "verify.py" in root:
                how = "local receipt (`verify.py`)"
            else:
                how = "no verifier"
            noun = "file" if len(modules) == 1 else "files"
            lean = f"{len(modules)} {noun}, {how}"
        rows.append(Row(
            name=name,
            status=WIRED if mentions_tree(research_job, name) else LOCAL,
            entry_points=entry,
            tests=tests,
            lean=lean,
            dependents=tuple(sorted(pinned_by[name])),
        ))
    return rows


def copy_holders(trees: Mapping[str, tuple[str, ...]]) -> dict[str, list[str]]:
    """For each hand-copied verifier file, the trees carrying it at their root."""
    return {
        copy: [name for name, files in trees.items() if copy in _root_files(files)]
        for copy in COPY_FILES
    }


def render_block(rows: Sequence[Row], holders: Mapping[str, Sequence[str]]) -> str:
    """The generated block, marker lines included, LF-terminated."""
    wired = sum(1 for row in rows if row.status == WIRED)
    lines = [BEGIN, HEADER, RULE]
    for row in rows:
        lines.append(
            f"| `{row.name}` | {row.status} | {_code_list(row.entry_points)} "
            f"| {row.tests} | {row.lean} | {_code_list(row.dependents)} |"
        )
    lines += [
        "",
        f"{len(rows)} trees; {wired} run by the workflow (gate 11); "
        f"{len(rows) - wired} local receipts only.",
        "",
        "## Hand copies",
        "",
    ]
    for copy in COPY_FILES:
        trees = holders.get(copy, [])
        lines.append(f"* `{copy}` ({len(trees)}): {_code_list(trees)}")
    lines.append(END)
    return "\n".join(lines) + "\n"


def splice(text: str, block: str) -> str:
    """Replace the marked region of ``text`` (LF-normalised) with ``block``."""
    lines = text.replace("\r\n", "\n").splitlines(keepends=True)
    begins = [i for i, line in enumerate(lines) if line.rstrip("\n") == BEGIN]
    ends = [i for i, line in enumerate(lines) if line.rstrip("\n") == END]
    if len(begins) != 1 or len(ends) != 1 or begins[0] > ends[0]:
        raise ValueError(
            f"{README_REL} must contain exactly one '{BEGIN}' line followed by "
            f"exactly one '{END}' line (found {len(begins)} and {len(ends)})"
        )
    return "".join(lines[:begins[0]]) + block + "".join(lines[ends[0] + 1:])


def expected_readme(repo: Path) -> str:
    """The README as the generator would write it."""
    current = (repo / README_REL).read_bytes().decode("utf-8")
    trees = group_trees(tracked_research_files(repo))
    return splice(current, render_block(build_rows(repo, trees), copy_holders(trees)))


def _table_trees(text: str) -> list[str]:
    inside = False
    names: list[str] = []
    for line in text.replace("\r\n", "\n").split("\n"):
        if line == BEGIN:
            inside = True
        elif line == END:
            break
        elif inside:
            match = _ROW_TREE.match(line)
            if match:
                names.append(match.group(1))
    return names


def problems(repo: Path = REPO, context_lines: int = 60) -> list[str]:
    """Empty when the README is current; otherwise lines naming the drift."""
    current = (repo / README_REL).read_bytes().decode("utf-8")
    try:
        expected = expected_readme(repo)
    except ValueError as exc:
        return [str(exc)]
    normalised = current.replace("\r\n", "\n")
    if normalised == expected:
        return []
    report = [f"{README_REL} is stale; regenerate it with: {REGENERATE}"]
    have, want = set(_table_trees(normalised)), set(_table_trees(expected))
    if want - have:
        report.append("trees missing from the table: " + ", ".join(sorted(want - have)))
    if have - want:
        report.append(
            "table rows that are not tracked trees: " + ", ".join(sorted(have - want))
        )
    diff = list(difflib.unified_diff(
        normalised.splitlines(), expected.splitlines(),
        f"{README_REL} (committed)", f"{README_REL} (generated)",
        lineterm="", n=0,
    ))
    report.extend(diff[:context_lines])
    if len(diff) > context_lines:
        report.append(f"... {len(diff) - context_lines} more diff lines")
    return report


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="exit 1 if the README is stale")
    mode.add_argument("--write", action="store_true", help="rewrite the README in place")
    args = parser.parse_args(argv)
    if args.check:
        found = problems(REPO)
        for line in found:
            print(line)
        if found:
            return 1
        print(f"{README_REL} is current")
        return 0
    try:
        text = expected_readme(REPO)
    except ValueError as exc:
        print(exc)
        return 1
    target = REPO / README_REL
    before = target.read_bytes()
    after = text.encode("utf-8")
    if before == after:
        print(f"{README_REL} already current")
    else:
        target.write_bytes(after)
        print(f"wrote {README_REL}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
